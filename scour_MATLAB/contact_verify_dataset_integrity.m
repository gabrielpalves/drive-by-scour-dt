function [integrity, sidecar_snapshots] = ...
        contact_verify_dataset_integrity( ...
            dataset_snapshot, descriptor_contract, verify_integrity)
%CONTACT_VERIFY_DATASET_INTEGRITY Bind parsed values to retained byte snapshots.

integrity = struct('status', 'SKIPPED', 'manifest_root', '', ...
    'state_digest_match', false, 'marker_match', false, ...
    'state_table_match', false, 'identity_table_match', false, ...
    'case_info_sha256', '', 'damage_states_sha256', '', ...
    'completion_marker_sha256', '', 'file_digests_sha256', '', ...
    'qualification_host_receipt_sha256', '');
sidecar_snapshots = {};
if ~verify_integrity
    return
end

required_dataset = {'dataset_dir', 'state_index', 'state_path', 'case_info', ...
    'state_data', 'state_table', 'strict_manifest', 'snapshots', ...
    'state_snapshot'};
if ~isstruct(dataset_snapshot) || ~isscalar(dataset_snapshot) || ...
        ~all(isfield(dataset_snapshot, required_dataset))
    error('contact_closure:BadDatasetSnapshot', ...
        'Strict integrity verification received an incomplete snapshot.');
end
dataset_dir = dataset_snapshot.dataset_dir;
state_path = dataset_snapshot.state_path;
case_info = dataset_snapshot.case_info;
state_data = dataset_snapshot.state_data;
state_table = dataset_snapshot.state_table;
strict_manifest = dataset_snapshot.strict_manifest;
snapshots = dataset_snapshot.snapshots;

if ~isstruct(strict_manifest) || ~isscalar(strict_manifest) || ...
        ~isfield(strict_manifest, 'root') || ...
        ~isfield(strict_manifest, 'names') || ...
        ~isfield(strict_manifest, 'sha256') || ...
        ~isfield(strict_manifest, 'file_digests_sha256') || ...
        ~isfield(strict_manifest, 'verified_state_indices') || ...
        ~isfield(strict_manifest, 'retained_snapshots') || ...
        ~ismember(dataset_snapshot.state_index, ...
            strict_manifest.verified_state_indices)
    error('contact_closure:BadDigestManifest', ...
        'Strict v2 manifest validation did not authenticate this state.');
end
if ~isequal(snapshots, strict_manifest.retained_snapshots)
    error('contact_closure:BadDatasetSnapshot', ...
        'Parsed dataset snapshots differ from the manifest-retained set.');
end

state_index = dataset_snapshot.state_index;
[~, state_name, state_extension] = fileparts(state_path);
state_filename = [state_name, state_extension];
state_file_snapshot = contact_named_file_snapshot( ...
    snapshots, state_filename);
case_snapshot = contact_named_file_snapshot(snapshots, 'case_info.mat');
states_snapshot = contact_named_file_snapshot( ...
    snapshots, 'damage_states.mat');
digests_snapshot = contact_named_file_snapshot( ...
    snapshots, 'file_digests.mat');
contact_assert_manifest_snapshot(strict_manifest, case_snapshot);
contact_assert_manifest_snapshot(strict_manifest, states_snapshot);
contact_assert_manifest_snapshot(strict_manifest, state_file_snapshot);
if ~strcmp(state_file_snapshot.sha256, ...
            dataset_snapshot.state_snapshot.sha256) || ...
        ~strcmp(digests_snapshot.sha256, ...
            strict_manifest.file_digests_sha256)
    error('contact_closure:StateDigestMismatch', ...
        'Strict manifest does not bind the parsed state/manifest bytes.');
end

marker_path = fullfile(dataset_dir, '_GENERATION_COMPLETE');
if ~isfile(marker_path)
    error('contact_closure:IncompleteDataset', ...
        'Integrity verification requires _GENERATION_COMPLETE.');
end
schema = contact_case_text(case_info, 'gen_schema', '');
fingerprint = contact_case_text(case_info, 'gen_fingerprint', '');
marker_snapshot = contact_validate_completion_marker_snapshot( ...
    marker_path, schema, fingerprint, strict_manifest.root);
sidecar_snapshots = {marker_snapshot};

if ~isstruct(state_table) || ~isscalar(state_table) || ...
        ~isfield(state_table, 'DamageStates') || ...
        size(state_table.DamageStates, 1) < state_index
    error('contact_closure:BadStateTable', ...
        'damage_states.mat has no DamageStates row %d.', state_index);
end
if ~isequal(double(state_table.DamageStates(state_index, :)), ...
        double(state_data.scour_vector(:)'))
    error('contact_closure:StateTableMismatch', ...
        'Saved scour_vector differs from DamageStates row %d.', state_index);
end
if isfield(state_table, 'BearingStates') && ...
        isfield(state_data, 'bearing_vector') && ...
        ~isequal(double(state_table.BearingStates(state_index, :)), ...
            double(state_data.bearing_vector(:)'))
    error('contact_closure:StateTableMismatch', ...
        'Saved bearing_vector differs from BearingStates row %d.', state_index);
end
if ~isfield(state_table, 'StateUID') || ...
        ~strcmp(char(string(state_table.StateUID{state_index})), ...
            descriptor_contract.state_uid) || ...
        ~isfield(state_table, 'StateSeedID') || ...
        state_table.StateSeedID(state_index) ~= ...
            descriptor_contract.state_seed_id || ...
        ~isfield(state_table, 'StateNamedStreamSeedID') || ...
        ~isequal(state_table.StateNamedStreamSeedID(state_index, :), ...
            state_data.state_named_stream_seed_id)
    error('contact_closure:StateIdentityMismatch', ...
        'Paper-1 identity tables disagree for state %d.', state_index);
end

host_receipt_path = fullfile( ...
    dataset_dir, 'qualification_host_receipt.json');
executed_path = fullfile(dataset_dir, 'qualification_executed.m');
receipt_exists = isfile(host_receipt_path);
executed_exists = isfile(executed_path);
if xor(receipt_exists, executed_exists)
    error('contact_closure:IncompleteDataset', ...
        ['qualification_host_receipt.json and qualification_executed.m ' ...
         'must either both be present or both be absent.']);
end
host_receipt_sha256 = '';
if receipt_exists
    expected_stage = contact_case_text(case_info, 'stage', '');
    environment_sha = contact_case_text( ...
        case_info, 'actual_matlab_environment_sha256', '');
    [~, ~, receipt_snapshot, executed_snapshot] = ...
        contact_validate_host_receipt( ...
            dataset_dir, host_receipt_path, expected_stage, case_info, ...
            '', environment_sha);
    host_receipt_sha256 = receipt_snapshot.sha256;
    sidecar_snapshots = [sidecar_snapshots; ...
        {receipt_snapshot; executed_snapshot}];
end

contact_assert_snapshot_set_unchanged( ...
    [snapshots; sidecar_snapshots]);
integrity.status = 'VERIFIED';
integrity.manifest_root = strict_manifest.root;
integrity.state_digest_match = true;
integrity.marker_match = true;
integrity.state_table_match = true;
integrity.identity_table_match = true;
integrity.case_info_sha256 = case_snapshot.sha256;
integrity.damage_states_sha256 = states_snapshot.sha256;
integrity.completion_marker_sha256 = marker_snapshot.sha256;
integrity.file_digests_sha256 = digests_snapshot.sha256;
integrity.qualification_host_receipt_sha256 = host_receipt_sha256;
end
