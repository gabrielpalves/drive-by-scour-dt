function sequences = local_legacy_mesh_sequences(geometries)
% Retained only to reproduce and reject the historical universal grid.
level_ids = {'M0', 'M1', 'M2', 'M3'};
per_bay = [1, 2, 4, 8];
h_m = [0.6, 0.3, 0.15, 0.075];
template = struct('geometry_id', '', 'level_id', '', ...
    'bridge_elements_per_sleeper_bay', 0, ...
    'rail_elements_per_sleeper_bay', 0, ...
    'bridge_nominal_h_m', 0, 'rail_nominal_h_m', 0);
sequences = repmat(template, numel(geometries)*numel(level_ids), 1);
row = 0;
for g = 1:numel(geometries)
    for m = 1:numel(level_ids)
        row = row+1;
        sequences(row) = struct('geometry_id', geometries(g).id, ...
            'level_id', level_ids{m}, ...
            'bridge_elements_per_sleeper_bay', per_bay(m), ...
            'rail_elements_per_sleeper_bay', per_bay(m), ...
            'bridge_nominal_h_m', h_m(m), ...
            'rail_nominal_h_m', h_m(m));
    end
end
end

