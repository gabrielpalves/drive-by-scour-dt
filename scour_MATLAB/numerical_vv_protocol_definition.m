%
% This function mirrors docs/numerical_vv_protocol.md.  It deliberately
% separates facts already fixed by that protocol from unresolved choices.  A
% caller must not turn an unresolved choice into a qualifying default.
%
% The returned contract is data only.  Calling this function does not execute
% or qualify a mesh/time-refinement study.

