    Calc.Profile.rail_end_clearance_m = Profile_cfg.rail_end_clearance_m;
end
if isfield(Profile_cfg,'rail_end_clearance_decision_id')
    expected_decision_id = 'paper1-rail-domain-clearance-c06-v1';
    decision_id = Profile_cfg.rail_end_clearance_decision_id;
    if ~isfield(Profile_cfg,'rail_end_clearance_m') || ...
            ~(ischar(decision_id) || ...
              (isstring(decision_id) && isscalar(decision_id))) || ...
            ~strcmp(char(decision_id),expected_decision_id) || ...
            ~isnumeric(Profile_cfg.rail_end_clearance_m) || ...
            ~isscalar(Profile_cfg.rail_end_clearance_m) || ...
            Profile_cfg.rail_end_clearance_m ~= 6
        error('A04_Options:MainCampaignRailEndClearance', ...
            ['Reviewed main-campaign clearance requires decision %s and ' ...
             'an explicit 6 m request.'],expected_decision_id);
    end
    Calc.Profile.rail_end_clearance_decision_id = char(decision_id);
end

