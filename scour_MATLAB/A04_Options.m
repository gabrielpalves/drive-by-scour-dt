function Calc = local_configure_f25_stored_type2(Calc, Profile_cfg)
% Source-locked F25 realization. B19 loads elevation only and preserves the
% live geometry; generator_source_root authenticates the asset bytes.
expected_contract = 'fernandes-2025-stored-type2-v1';
expected_asset = 'Calc.ProfileData15_05.mat';
expected_sha256 = ...
    '71c69d9923bdc184a2c8448e0e0e6debb1670302908e093b758f57c36147465d';
required = {'profile_contract','asset_name','asset_sha256'};
missing = setdiff(required, fieldnames(Profile_cfg));
if ~isempty(missing) || ...
        ~strcmp(Profile_cfg.profile_contract, expected_contract) || ...
        ~strcmp(Profile_cfg.asset_name, expected_asset) || ...
        ~strcmp(Profile_cfg.asset_sha256, expected_sha256)
    error('A04_Options:F25ProfileContract', ...
        ['f25_stored_type2 requires the reviewed contract, asset name, and ' ...
         'SHA-256 supplied by ttbi.f25_experiment_config.']);
end
Calc.Profile.Type = 2;
Calc.Profile.text = 'Fernandes 2025 stored Type-2 realization';
Calc.Profile.profile_contract = expected_contract;
Calc.Profile.source_asset_name = expected_asset;
Calc.Profile.source_asset_sha256 = expected_sha256;
Calc.Profile.intensity = 1;
end

function Calc = local_configure_fra_v2(Calc, Profile_cfg)
% One executable spectral contract shared by fixed and per-state profiles.
expected_contract = 'fra-v2-class4-cycles-per-m-v1';
if ~isfield(Profile_cfg, 'spectrum_contract')
    Profile_cfg.spectrum_contract = expected_contract;
elseif ~strcmp(Profile_cfg.spectrum_contract, expected_contract)
    error('A04_Options: unexpected FRA-v2 spectrum contract "%s".', ...
        Profile_cfg.spectrum_contract);
end
A_v_classes = [1.2107, 1.0181, 0.6816, 0.5376, 0.2095, 0.0339];
if ~isfield(Profile_cfg, 'fra_class') || ...
        ~isscalar(Profile_cfg.fra_class) || ...
        Profile_cfg.fra_class ~= round(Profile_cfg.fra_class) || ...
        Profile_cfg.fra_class < 1 || Profile_cfg.fra_class > 6
    error('A04_Options: fra_class must be one integer in 1..6.');
end
Calc.Profile.Type = 1;
Calc.Profile.PSD_Y_fun = @(spaf,inputs) ...
    (inputs(1)*inputs(2)*inputs(3)^2) ./ ...
    ((spaf.^2).*(spaf.^2+inputs(3)^2))*inputs(4);
Calc.Profile.inputs(1) = 0.25;
Calc.Profile.inputs(2) = A_v_classes(Profile_cfg.fra_class);
% B19's axis is cycles/m. Convert Omega_c from rad/m and A_v from
% cm^2*rad/m consistently; see smoke_audit.m.
Calc.Profile.inputs(3) = 0.8245/(2*pi);
Calc.Profile.inputs(4) = 1e-4/(2*pi);
Calc.Profile.min_WaveLength = 1.524;
Calc.Profile.max_WaveLength = 304.8;
Calc.Profile.text = sprintf('FRA-v2 class %d', Profile_cfg.fra_class);
Calc.Profile.fra_class = Profile_cfg.fra_class;
Calc.Profile.spectrum_contract = expected_contract;
if isfield(Profile_cfg, 'phase_seed')
    Calc.Profile.phase_seed = Profile_cfg.phase_seed;
end
if isfield(Profile_cfg, 'jitter_sd_m')
    Calc.Profile.jitter_sd_m = Profile_cfg.jitter_sd_m;
end
