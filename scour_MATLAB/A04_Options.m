% ------------------------- Track irregularity ----------------------------
% The profile MODE is chosen per-run in A00 and passed in as Profile_cfg
% (optional 3rd argument; omitted -> 'fixed'). Registered modes:
%   'fixed'        one fixed-phase FRA-v2 class-4 realization shared by states
%   'fixed_scaled' the same fixed-phase FRA-v2 realization times intensity
%   'psd_fra'      the SAME FRA-v2 spectrum/cutoffs with state-specific phases
%                  (class from Profile_cfg.fra_class; 1 = worst, 6 = best).
%   'f25_stored_type2' the Fernandes (2025) stored Type-2 realization; this
%                  mode is reserved for the isolated F25 experiment.
% Thus fixed -> psd_fra changes the phase-realization distribution only, not
% the spectral law or amplitude. Ref: Berawi (2013), "Improving railway track
% maintenance using PSD".
if nargin < 3 || isempty(Profile_cfg) || ~isfield(Profile_cfg, 'mode')
    Profile_cfg = struct('mode', 'fixed');
end
Calc = struct();

switch Profile_cfg.mode

    case 'fixed'
        % The fixed baseline is generated by the exact same FRA-v2 helper as
        % psd_fra, with one reviewed seed shared across every state.
        if ~isfield(Profile_cfg, 'fra_class')
            Profile_cfg.fra_class = 4;
        end
        if ~isfield(Profile_cfg, 'phase_seed')
            Profile_cfg.phase_seed = 20260728;
        end
        Calc = local_configure_fra_v2(Calc, Profile_cfg);

    case 'fixed_scaled'
        % Legacy/non-registered sensitivity mode: same fixed FRA-v2 phase,
        % multiplied after generation by the requested intensity.
        if ~isfield(Profile_cfg, 'fra_class')
            Profile_cfg.fra_class = 4;
        end
        if ~isfield(Profile_cfg, 'phase_seed')
            Profile_cfg.phase_seed = 20260728;
        end
        Calc = local_configure_fra_v2(Calc, Profile_cfg);
        Calc.Profile.intensity = Profile_cfg.intensity;

    case 'psd_fra'
        Calc = local_configure_fra_v2(Calc, Profile_cfg);

    case 'f25_stored_type2'
        Calc = local_configure_f25_stored_type2(Calc, Profile_cfg);

    otherwise
        error('A04_Options: unknown Profile_cfg.mode "%s"', Profile_cfg.mode);
end

% Main-campaign calls carry both reviewed fields.  A numeric request without a
% decision ID remains available only to nonproduction clearance studies and
% upstream/standalone callers; omission leaves B43's compatibility fallback.
