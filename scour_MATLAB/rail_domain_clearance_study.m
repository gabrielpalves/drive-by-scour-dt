function local_write_report(path,verdict,summary,C)
lines = { ...
    '# Rail-domain clearance study';''; ...
    sprintf('- Run kind: `%s`',verdict.run_kind); ...
    sprintf('- Status: **%s**',verdict.overall_status); ...
    sprintf('- Production selection: `%s`', ...
        verdict.production_selection_status); ...
    sprintf('- Diagnostic reference: %.0f m', ...
        verdict.diagnostic_clearance_m); ...
    sprintf('- Reason: %s',verdict.reason);''; ...
    'This verdict is limited to finite-rail-domain model-form selection.'; ...
    'It does not authorize physical validation or general numerical V&V.';''; ...
    '## Frozen rule';'';C.selection_rule;''};
if ~isempty(verdict.production_clearance_m)
    lines{end+1} = sprintf('Selected production clearance: **%.0f m**.', ...
        verdict.production_clearance_m);
    lines{end+1} = '';
end
if ~isempty(summary)
    lines{end+1} = '## Group comparisons';
    lines{end+1} = '';
    lines{end+1} = ['| Geometry | Operating point | Comparison | Worst NRMSE | ' ...
        'Worst NMAX | Min corr. | Pass |'];
    lines{end+1} = '|---|---|---|---:|---:|---:|:---:|';
    comparison_lines = cell(height(summary),1);
    for row = 1:height(summary)
        comparison_lines{row} = sprintf( ...
            '| %s | %s | %s | %.6g | %.6g | %.6g | %d |', ...
            summary.geometry_id(row),summary.operating_point_id(row), ...
            summary.comparison_id(row),summary.worst_nrmse(row), ...
            summary.worst_normalized_max_error(row), ...
            summary.worst_correlation(row),summary.comparison_pass(row));
    end
    lines = [lines;comparison_lines];
end
local_write_text(path,[strjoin(lines,newline),newline]);
end

function source = local_git_identity()
matlab_root = fileparts(mfilename('fullpath'));
repo_root = fileparts(matlab_root);
[commit_status,commit_text] = system(sprintf( ...
    'git -C "%s" rev-parse HEAD',repo_root));
[dirty_status,dirty_text] = system(sprintf( ...
    'git -C "%s" status --porcelain --untracked-files=normal',repo_root));
if commit_status == 0
    commit = strtrim(commit_text);
else
    commit = 'UNAVAILABLE';
end
clean = commit_status == 0 && dirty_status == 0 && isempty(strtrim(dirty_text));
source = struct('commit',commit,'clean',logical(clean));
end

function inventory = local_artifact_inventory(root,names)
inventory = repmat(struct('path','','sha256','','bytes',0),numel(names),1);
for k = 1:numel(names)
    path = fullfile(root,names{k}); info = dir(path);
    inventory(k).path = names{k};
    inventory(k).sha256 = numerical_vv_file_sha256(path);
    inventory(k).bytes = info.bytes;
end
end

function names = local_file_names(root,excluded)
entries = dir(root); entries = entries(~[entries.isdir]);
names = sort(reshape({entries.name},[],1));
names = setdiff(names,excluded,'stable');
end

function local_write_json(path,value)
local_write_text(path,[jsonencode(value,'PrettyPrint',true),newline]);
end

function local_write_text(path,value)
bytes = unicode2native(char(value),'UTF-8');
fid = fopen(path,'wb');
if fid < 0
    error('rail_domain_clearance:FileWrite','Could not write %s.',path);
end
cleanup = onCleanup(@() fclose(fid));
written = fwrite(fid,bytes,'uint8');
if written ~= numel(bytes)
    error('rail_domain_clearance:FileWrite','Short write to %s.',path);
end
end

