function contact_assert_closure_host_matches_datasets(attestation, datasets)
%CONTACT_ASSERT_CLOSURE_HOST_MATCHES_DATASETS Reject physical-host drift.

mapping = { ...
    'hostname', 'qualification_hostname'; ...
    'cpu_identifier', 'qualification_cpu_identifier'; ...
    'logical_processors', 'qualification_logical_processors'; ...
    'matlab_max_threads', 'qualification_matlab_max_threads'; ...
    'computer_arch', 'qualification_computer_arch'};
for stage_index = 1:numel(datasets)
    for field_index = 1:size(mapping, 1)
        closure_field = mapping{field_index, 1};
        dataset_field = mapping{field_index, 2};
        if ~isequal(attestation.(closure_field), ...
                datasets(stage_index).(dataset_field))
            error('contact_closure_gate:ClosureHostMismatch', ...
                ['Closure execution host differs from %s qualification ' ...
                 'receipt at %s.'], datasets(stage_index).stage, ...
                closure_field);
        end
    end
end
end
