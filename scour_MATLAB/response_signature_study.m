function polygon = local_polygon_harmonic_report( ...
        item,design,healthy_vehicle,damaged_vehicle,healthy_bridge,damaged_bridge)
row = double(item.damage.oor_poly);
if ~isequal(size(row),[1 5])
    error('response_signature:PolygonDescriptor', ...
        'The polygon response fixture requires one [veh wheel n amp phase] row.');
end
speed_mps = design.speed_kmh/3.6;
target_hz = row(3)*speed_mps/(2*pi*item.damage.oor_radius);
if abs(target_hz-design.polygon_harmonic_frequency_hz) > ...
        10*eps(max(1,target_hz))
    error('response_signature:PolygonFrequencyMismatch', ...
        'Catalog and response metric disagree on polygon forcing frequency.');
end
polygon = struct( ...
    'vehicle_index',row(1), ...
    'wheel_index',row(2), ...
    'harmonic_order',row(3), ...
    'path_amplitude_m',row(4), ...
    'phase_rad',row(5), ...
    'wheel_radius_m',double(item.damage.oor_radius), ...
    'speed_mps',speed_mps, ...
    'target_frequency_hz',target_hz, ...
    'frequency_definition','harmonic_order*speed_mps/(2*pi*wheel_radius_m)', ...
    'metric_definition',[ ...
        'exact-frequency least-squares sinusoidal amplitude plus nearest ' ...
        'fixed-Welch-bin PSD density; independent of reporting bands'], ...
    'vehicle_response',local_harmonic_comparison( ...
        healthy_vehicle,damaged_vehicle), ...
    'bridge_response',local_harmonic_comparison( ...
        healthy_bridge,damaged_bridge));
end

function comparison = local_bridge_extreme_comparison(healthy,damaged)
h = {healthy.bending_moment_extreme;healthy.shear_extreme};
d = {damaged.bending_moment_extreme;damaged.shear_extreme};
healthy_signed = cellfun(@(x) x.signed_value,h);
intervention_signed = cellfun(@(x) x.signed_value,d);
healthy_absolute = cellfun(@(x) x.absolute_value,h);
intervention_absolute = cellfun(@(x) x.absolute_value,d);
comparison = table( ...
    {'bending_moment_extreme';'shear_extreme'}, ...
    {'N m';'N'}, ...
    healthy_signed,intervention_signed, ...
    intervention_signed-healthy_signed, ...
    healthy_absolute,intervention_absolute, ...
    intervention_absolute-healthy_absolute, ...
    cellfun(@(x) x.bridge_x_m,h),cellfun(@(x) x.bridge_x_m,d), ...
    cellfun(@(x) x.time_s,h),cellfun(@(x) x.time_s,d), ...
    'VariableNames',{'quantity','unit','healthy_signed_value', ...
    'intervention_signed_value','delta_signed_value','healthy_absolute_value', ...
    'intervention_absolute_value','delta_absolute_value','healthy_bridge_x_m', ...
    'intervention_bridge_x_m','healthy_time_s','intervention_time_s'});
end

function comparison = local_bridge_event_comparison(healthy,damaged)
h = healthy.leading_wheel_bridge_events;
d = damaged.leading_wheel_bridge_events;
if ~isequal(h.event,d.event) || ...
        ~isequal(h.target_global_x_m,d.target_global_x_m) || ...
        ~isequal(h.sample_index,d.sample_index)
    error('response_signature:BridgeEventCrnMismatch', ...
        'Healthy/intervention bridge entry/exit event grids do not align.');
end
required_lengths = [numel(h.event),numel(h.target_global_x_m), ...
    numel(h.realized_global_x_m),numel(d.realized_global_x_m), ...
    numel(h.time_s),numel(d.time_s),numel(h.midspan_displacement_m), ...
    numel(d.midspan_displacement_m),numel(h.midspan_acceleration_mps2), ...
    numel(d.midspan_acceleration_mps2)];
if any(required_lengths ~= 2)
    error('response_signature:BridgeEventShape', ...
        'Bridge event report requires exactly one entry and one exit value.');
end
event = {h.event{1};h.event{1};h.event{2};h.event{2}};
quantity = {'midspan_displacement';'midspan_acceleration'; ...
    'midspan_displacement';'midspan_acceleration'};
unit = {'m';'m/s^2';'m';'m/s^2'};
target_global_x_m = [h.target_global_x_m(1);h.target_global_x_m(1); ...
    h.target_global_x_m(2);h.target_global_x_m(2)];
healthy_realized_global_x_m = [h.realized_global_x_m(1); ...
    h.realized_global_x_m(1);h.realized_global_x_m(2); ...
    h.realized_global_x_m(2)];
intervention_realized_global_x_m = [d.realized_global_x_m(1); ...
    d.realized_global_x_m(1);d.realized_global_x_m(2); ...
    d.realized_global_x_m(2)];
healthy_time_s = [h.time_s(1);h.time_s(1);h.time_s(2);h.time_s(2)];
intervention_time_s = [d.time_s(1);d.time_s(1);d.time_s(2);d.time_s(2)];
healthy_value = [h.midspan_displacement_m(1); ...
    h.midspan_acceleration_mps2(1);h.midspan_displacement_m(2); ...
    h.midspan_acceleration_mps2(2)];
intervention_value = [d.midspan_displacement_m(1); ...
    d.midspan_acceleration_mps2(1);d.midspan_displacement_m(2); ...
    d.midspan_acceleration_mps2(2)];
comparison = table(event,quantity,unit, ...
    target_global_x_m,healthy_realized_global_x_m, ...
    intervention_realized_global_x_m,healthy_time_s,intervention_time_s, ...
    healthy_value,intervention_value,intervention_value-healthy_value, ...
    'VariableNames',{'event','quantity','unit','target_global_x_m', ...
    'healthy_realized_global_x_m','intervention_realized_global_x_m', ...
    'healthy_time_s','intervention_time_s','healthy_value', ...
    'intervention_value','delta'});
end

function contact = local_contact_pair(healthy,damaged)
if ~isequal(healthy.x_m,damaged.x_m) || ...
        ~isequal(healthy.on_track_mask,damaged.on_track_mask)
    error('response_signature:ContactCrnMismatch', ...
        'Healthy/intervention contact paths do not share one exact grid.');
end
contact = struct();
contact.x_m = healthy.x_m;
contact.on_track_mask = healthy.on_track_mask;
contact.healthy_force_n = healthy.force_n;
contact.intervention_force_n = damaged.force_n;
contact.force_delta_n = damaged.force_n-healthy.force_n;
contact.history_scope = 'all four wheels of the leading vehicle';
contact.healthy_per_wheel = healthy.per_wheel;
contact.intervention_per_wheel = damaged.per_wheel;
contact.healthy_per_vehicle = healthy.per_vehicle;
contact.intervention_per_vehicle = damaged.per_vehicle;
contact.summary = local_contact_comparison(healthy,damaged);
if ~isequaln(healthy.registered_policy,damaged.registered_policy)
    error('response_signature:ContactPolicyMismatch', ...
        'Healthy/intervention runs must use one identical contact policy.');
end
contact.registered_policy = healthy.registered_policy;
contact.healthy_aggregate_tensile_peak_n = ...
    healthy.aggregate_tensile_peak_n;
contact.intervention_aggregate_tensile_peak_n = ...
    damaged.aggregate_tensile_peak_n;
contact.healthy_aggregate_positive_fraction = ...
    healthy.aggregate_positive_fraction;
contact.intervention_aggregate_positive_fraction = ...
    damaged.aggregate_positive_fraction;
contact.healthy_registered_admissible = healthy.registered_admissible;
contact.intervention_registered_admissible = damaged.registered_admissible;
contact.pair_registered_admissible = ...
    healthy.registered_admissible && damaged.registered_admissible;
contact.healthy_lost_track = healthy.lost_track;
contact.intervention_lost_track = damaged.lost_track;
contact.healthy_lost_bridge = healthy.lost_bridge;
contact.intervention_lost_bridge = damaged.lost_bridge;
end

function summary = local_contact_summary(contact)
summary = contact.per_wheel;
end

function comparison = local_contact_comparison(healthy,damaged)
h = healthy.per_wheel;
d = damaged.per_wheel;
key_names = {'vehicle_index','wheel_index','wheel','on_track_sample_count'};
for k = 1:numel(key_names)
    if ~isequal(h.(key_names{k}),d.(key_names{k}))
        error('response_signature:ContactKeyMismatch', ...
            'Healthy/intervention per-wheel contact rows do not align.');
    end
end
comparison = table( ...
    h.vehicle_index,h.wheel_index,h.wheel,h.on_track_sample_count, ...
    h.signed_tensile_peak_n,d.signed_tensile_peak_n, ...
    d.signed_tensile_peak_n-h.signed_tensile_peak_n, ...
    h.compressive_minimum_n,d.compressive_minimum_n, ...
    d.compressive_minimum_n-h.compressive_minimum_n, ...
    h.absolute_peak_n,d.absolute_peak_n, ...
    d.absolute_peak_n-h.absolute_peak_n, ...
    h.positive_fraction,d.positive_fraction, ...
    d.positive_fraction-h.positive_fraction, ...
    'VariableNames',{'vehicle_index','wheel_index','wheel', ...
    'on_track_sample_count','healthy_signed_tensile_peak_n', ...
    'intervention_signed_tensile_peak_n','delta_signed_tensile_peak_n', ...
    'healthy_compressive_minimum_n','intervention_compressive_minimum_n', ...
    'delta_compressive_minimum_n','healthy_absolute_peak_n', ...
    'intervention_absolute_peak_n','delta_absolute_peak_n', ...
    'healthy_positive_fraction','intervention_positive_fraction', ...
    'delta_positive_fraction'});
end

function selected = local_select_catalog(catalog,names)
available = {catalog.name};
indices = zeros(1,numel(names));
for k = 1:numel(names)
    found = find(strcmp(available,names{k}));
    if numel(found) ~= 1
        error('response_signature:UnknownIntervention', ...
            'Unknown intervention "%s". Available: %s.', ...
            names{k},strjoin(available,', '));
    end
    indices(k) = found;
end
if numel(unique(indices)) ~= numel(indices)
    error('response_signature:DuplicateIntervention', ...
        'requested_names must not contain duplicate interventions.');
end
selected = catalog(indices);
end

function names = local_names(names)
if ischar(names)
    names = {names};
elseif isstring(names)
    names = cellstr(names(:));
elseif iscell(names)
    names = names(:)';
else
    error('response_signature:InterventionNames', ...
        'requested_names must be text or a cell array of text.');
end
if any(~cellfun(@(x) ischar(x) && isrow(x) && ~isempty(x),names))
    error('response_signature:InterventionNames', ...
        'Every requested intervention name must be nonempty text.');
end
end
