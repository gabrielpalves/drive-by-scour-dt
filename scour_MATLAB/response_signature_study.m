function report = response_signature_study(requested_names,design)
%RESPONSE_SIGNATURE_STUDY Exploratory paired TTBI mechanism fingerprints.
%
% report = response_signature_study()
% report = response_signature_study({'scour','wheel_polygonization'})
% report = response_signature_study(requested_names,design)
%
% One fixed passage is cloned exactly and one explicit intervention is made
% active at a time.  The report contains exact matrix/path deltas, matched
% bridge modes, vehicle and bridge RMS/peak/PSD-band metrics, all four
% leading-vehicle contact histories, and all-vehicle per-wheel contact
% diagnostics.  It is intentionally marked exploratory/nonqualifying: it
% does not replace the registered 50-passage, multi-level CRN study.

if nargin < 2
    design = struct();
end
[healthy_damage,catalog,design] = ...
    response_signature_damage_catalog(design);
if nargin < 1 || isempty(requested_names)
    requested_names = {catalog.name};
end
requested_names = local_names(requested_names);
catalog = local_select_catalog(catalog,requested_names);

fprintf(['RESPONSE SIGNATURE STUDY: exploratory/nonqualifying; ' ...
    '1 healthy + %d one-factor passage(s)\n'],numel(catalog));
healthy_run = response_signature_run_one(healthy_damage,design);
healthy_vehicle_metrics = local_metrics(healthy_run.vehicle, ...
    healthy_run.controls.time_s,design);
healthy_bridge_metrics = local_metrics(healthy_run.bridge, ...
    healthy_run.controls.time_s,design);

report = struct();
report.schema = 'ttbi-paired-response-signatures-v2';
report.status = 'exploratory/nonqualifying';
report.study_design = design;
report.crn_contract = [ ...
    'Every intervention reuses exactly the same speed, temperature, ' ...
    'vehicle descriptor, FRA-v2 realization, time grid, wheel positions, ' ...
    'and fixed mesh geometry. Damage-induced placement state, including ' ...
    'track-frame offset, is reported separately and is not a CRN control.'];
report.crn_control_fields = fieldnames(healthy_run.controls);
report.rayleigh_damping_contract = [ ...
    'Bridge-stiffness interventions use state-specific Rayleigh damping: ' ...
    'B24 recomputes bridge damping and the rail damping reference follows ' ...
    'the state bridge modes. Beam/model C deltas are retained and these ' ...
    'pairs are not described as fixed-C or K-only counterfactuals.'];
report.contact_admissibility_policy = healthy_run.contact.registered_policy;
report.polygon_harmonic_contract = [ ...
    'Target frequency is n*v/(2*pi*R). Exact-frequency least-squares ' ...
    'amplitude and nearest-Welch-bin density are reported independently ' ...
    'of the 0.2-15 Hz reporting band.'];
report.interpretation_contract = [ ...
    'Physical response directions are reported, never required. Positive ' ...
    'contact force denotes bilateral-solver tensile demand, not simulated ' ...
    'separation or re-contact.'];
report.limitations = { ...
    ['One deterministic representative passage and one representative ' ...
     'level per intervention only.']; ...
    ['Not the registered 50-passage repeated-observation study and not a ' ...
     'basis for confidence intervals or population inference.']; ...
    ['Bridge-only modes are matched here; coupled track-bridge modal ' ...
     'matching remains part of numerical V&V.']; ...
    ['Contact admissibility uses the source-locked 24 kN peak and 0.002 ' ...
     'on-track positive-fraction limits; any positive reaction remains ' ...
     'reported as bilateral-solver tensile demand.']};
report.healthy = local_healthy_report( ...
    healthy_run,healthy_vehicle_metrics,healthy_bridge_metrics);
report.pairs = repmat(local_empty_pair(),numel(catalog),1);

for k = 1:numel(catalog)
    item = catalog(k);
    fprintf('  [%d/%d] %s: %s\n',k,numel(catalog), ...
        item.name,item.level_label);
    damaged_run = response_signature_run_one(item.damage,design);
    if ~isequaln(healthy_run.controls,damaged_run.controls)
        error('response_signature:CrnMismatch', ...
            '%s changed a non-intervention passage control.',item.name);
    end
    delta = local_physics_delta(healthy_run.physics,damaged_run.physics);
    local_assert_mechanism_boundary( ...
        item,healthy_run.physics,damaged_run.physics,delta);

    damaged_vehicle_metrics = local_metrics( ...
        damaged_run.vehicle,damaged_run.controls.time_s,design);
    damaged_bridge_metrics = local_metrics( ...
        damaged_run.bridge,damaged_run.controls.time_s,design);
    pair = local_empty_pair();
    pair.name = item.name;
    pair.role = item.role;
    pair.mechanism = item.mechanism;
    pair.level_label = item.level_label;
    pair.changed_damage_fields = item.changed_damage_fields;
    pair.damage = item.damage;
    pair.crn_controls_exactly_equal = true;
    pair.crn_control_fields = fieldnames(healthy_run.controls);
    pair.state_specific_geometry = struct( ...
        'healthy',healthy_run.geometry, ...
        'intervention',damaged_run.geometry, ...
        'track_frame_offset_delta_m', ...
            damaged_run.geometry.track_frame_offset_m - ...
            healthy_run.geometry.track_frame_offset_m);
    pair.physics_boundary_role = item.first_changed_quantity;
    pair.physics_delta = delta;
    pair.physics_change_counts = local_change_counts(delta);
    pair.rayleigh_damping = local_rayleigh_damping_report(item,delta);
    pair.modal = local_modal_pair(healthy_run.modal,damaged_run.modal);
    pair.vehicle_metric_comparison = local_metric_comparison( ...
        healthy_vehicle_metrics,damaged_vehicle_metrics);
    pair.vehicle_waveform_delta = ...
        damaged_run.vehicle.signal-healthy_run.vehicle.signal;
    pair.bridge_metric_comparison = local_metric_comparison( ...
        healthy_bridge_metrics,damaged_bridge_metrics);
    pair.bridge_waveform_delta = ...
        damaged_run.bridge.signal-healthy_run.bridge.signal;
    pair.bridge_extreme_comparison = local_bridge_extreme_comparison( ...
        healthy_run.bridge,damaged_run.bridge);
    pair.bridge_event_comparison = local_bridge_event_comparison( ...
        healthy_run.bridge,damaged_run.bridge);
    pair.contact = local_contact_pair( ...
        healthy_run.contact,damaged_run.contact);
    pair.bilateral_contact_admissible = ...
        pair.contact.pair_registered_admissible;
    if strcmp(item.name,'wheel_polygonization')
        pair.polygon_harmonic = local_polygon_harmonic_report( ...
            item,design,healthy_vehicle_metrics,damaged_vehicle_metrics, ...
            healthy_bridge_metrics,damaged_bridge_metrics);
    end
    pair.vehicle_response_changed_exactly = ...
        ~isequal(healthy_run.vehicle.signal,damaged_run.vehicle.signal);
    pair.response_direction_gate = 'none: report signed paired differences';
    report.pairs(k) = pair;
end

fprintf(['RESPONSE SIGNATURE STUDY COMPLETE: %d paired fingerprints; ' ...
    'no response-direction threshold applied; contact policy classified\n'], ...
    numel(report.pairs));
end

