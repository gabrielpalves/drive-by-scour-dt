function damping = local_rayleigh_damping_report(item,delta)
is_state_specific = strcmp(item.first_changed_quantity, ...
    'bridge_stiffness_state_specific_rayleigh_damping');
damping = struct( ...
    'state_specific_rayleigh_recomputed',is_state_specific, ...
    'beam_C_delta_nnz',nnz(delta.beam_C), ...
    'model_C_delta_nnz',nnz(delta.model_C), ...
    'beam_C_delta_frobenius_norm',norm(delta.beam_C,'fro'), ...
    'model_C_delta_frobenius_norm',norm(delta.model_C,'fro'));
if is_state_specific
    damping.interpretation = [ ...
        'Bridge K changed and production recomputed state-specific bridge ' ...
        'and rail Rayleigh damping; this is a K+C dynamic intervention, ' ...
        'not a fixed-C K-only counterfactual.'];
else
    damping.interpretation = [ ...
        'Any C delta shown here follows the declared non-structural ' ...
        'mechanism boundary; no bridge-stiffness Rayleigh retuning occurred.'];
end
end

function local_assert_mechanism_boundary(item,healthy,damaged,delta)
assert(isequal(healthy.beam_M,damaged.beam_M) && ...
    isequal(healthy.model_M,damaged.model_M), ...
    'response_signature:MassChanged', ...
    '%s changed mass, outside its documented boundary.',item.name);

path_same = isequal(healthy.wheel_h_m,damaged.wheel_h_m) && ...
    isequal(healthy.wheel_hd_mps,damaged.wheel_hd_mps) && ...
    isequal(healthy.wheel_hdd_mps2,damaged.wheel_hdd_mps2);
switch item.first_changed_quantity
    case 'bridge_stiffness_state_specific_rayleigh_damping'
        assert(nnz(delta.beam_K) > 0 && nnz(delta.model_K) > 0 && ...
            nnz(delta.beam_C) > 0 && nnz(delta.model_C) > 0 && path_same, ...
            'response_signature:PhysicsBoundary', ...
            ['%s did not exhibit the declared bridge-stiffness plus ' ...
             'state-specific Rayleigh-damping boundary.'], ...
            item.name);
    case 'track_stiffness_damping'
        assert(isequal(healthy.beam_K,damaged.beam_K) && ...
            isequal(healthy.beam_C,damaged.beam_C) && ...
            nnz(delta.model_K) > 0 && nnz(delta.model_C) > 0 && path_same, ...
            'response_signature:PhysicsBoundary', ...
            '%s did not remain inside the track K/C boundary.',item.name);
    case 'track_stiffness_only'
        assert(isequal(healthy.beam_K,damaged.beam_K) && ...
            isequal(healthy.beam_C,damaged.beam_C) && ...
            nnz(delta.model_K) > 0 && nnz(delta.model_C) == 0 && path_same, ...
            'response_signature:PhysicsBoundary', ...
            '%s did not remain inside the track-K boundary.',item.name);
    case 'track_damping_only'
        assert(isequal(healthy.beam_K,damaged.beam_K) && ...
            isequal(healthy.beam_C,damaged.beam_C) && ...
            nnz(delta.model_K) == 0 && nnz(delta.model_C) > 0 && path_same, ...
            'response_signature:PhysicsBoundary', ...
            '%s did not remain inside the track-C boundary.',item.name);
    case 'wheel_path'
        assert(isequal(healthy.beam_K,damaged.beam_K) && ...
            isequal(healthy.beam_C,damaged.beam_C) && ...
            isequal(healthy.model_K,damaged.model_K) && ...
            isequal(healthy.model_C,damaged.model_C) && ...
            nnz(delta.wheel_h_m) > 0 && nnz(delta.wheel_hd_mps) > 0 && ...
            nnz(delta.wheel_hdd_mps2) > 0, ...
            'response_signature:PhysicsBoundary', ...
            '%s did not remain inside the wheel-path boundary.',item.name);
    otherwise
        error('response_signature:UnknownBoundary', ...
            'Unknown first-changed quantity %s.',item.first_changed_quantity);
end
end

function modal = local_modal_pair(healthy,damaged)
if ~isequal(healthy.mass_matrix,damaged.mass_matrix)
    error('response_signature:ModalMassMismatch', ...
        'MAC matching requires one common unchanged bridge mass matrix.');
end
if numel(healthy.frequency_hz) < 5 || numel(damaged.frequency_hz) < 5 || ...
        size(healthy.mode_shapes,2) < 5 || size(damaged.mode_shapes,2) < 5
    error('response_signature:MissingModes', ...
        'At least five healthy and five intervention bridge modes are required.');
end
n_reference = 5;
n_candidate = min(10,numel(damaged.frequency_hz));
if n_candidate < n_reference || size(damaged.mode_shapes,2) < n_candidate
    error('response_signature:MissingModes', ...
        'At least five candidate bridge modes are required for matching.');
end
phi_h = healthy.mode_shapes(:,1:n_reference);
phi_d = damaged.mode_shapes(:,1:n_candidate);
mass = healthy.mass_matrix;
cross = phi_h'*mass*phi_d;
norm_h = real(diag(phi_h'*mass*phi_h));
norm_d = real(diag(phi_d'*mass*phi_d));
mac = abs(cross).^2 ./ (norm_h*norm_d');
matched = local_best_assignment(mac);
indices = sub2ind(size(mac),(1:n_reference)',matched(:));
modal = struct();
modal.matching_method = ...
    ['exhaustive maximum summed mass-metric MAC over first 10 candidates; ' ...
     'MAC denominator explicitly normalizes both mode shapes'];
modal.reference_mode = (1:n_reference)';
modal.intervention_mode = matched(:);
modal.mac = mac(indices);
modal.mac_matrix = mac;
modal.healthy_frequency_hz = healthy.frequency_hz(1:n_reference);
modal.intervention_frequency_hz = damaged.frequency_hz(matched);
modal.frequency_delta_hz = modal.intervention_frequency_hz - ...
    modal.healthy_frequency_hz;
end

function assignment = local_best_assignment(mac)
n_reference = size(mac,1);
n_candidate = size(mac,2);
combinations = nchoosek(1:n_candidate,n_reference);
best_score = -Inf;
assignment = zeros(1,n_reference);
for row = 1:size(combinations,1)
    candidates = perms(combinations(row,:));
    for k = 1:size(candidates,1)
        indices = sub2ind(size(mac),(1:n_reference)',candidates(k,:)');
        score = sum(mac(indices));
        if score > best_score
            best_score = score;
            assignment = candidates(k,:);
        end
    end
end
end

function comparison = local_metric_comparison(healthy,damaged)
h = healthy.summary;
d = damaged.summary;
key_names = {'channel','signal_unit','psd_band','band_low_hz','band_high_hz', ...
    'realized_band_low_hz','realized_band_high_hz','realized_bin_count', ...
    'psd_density_unit','psd_band_energy_unit'};
for k = 1:numel(key_names)
    if ~isequal(h.(key_names{k}),d.(key_names{k}))
        error('response_signature:MetricKeyMismatch', ...
            'Healthy/intervention metric rows do not align.');
    end
end
comparison = table( ...
    h.channel,h.signal_unit,h.psd_band,h.band_low_hz,h.band_high_hz, ...
    h.realized_band_low_hz,h.realized_band_high_hz,h.realized_bin_count, ...
    h.psd_density_unit,h.psd_band_energy_unit, ...
    h.signal_rms,d.signal_rms,d.signal_rms-h.signal_rms, ...
    h.signal_abs_peak,d.signal_abs_peak, ...
    d.signal_abs_peak-h.signal_abs_peak, ...
    h.psd_band_energy,d.psd_band_energy, ...
    d.psd_band_energy-h.psd_band_energy, ...
    'VariableNames',{'channel','signal_unit','psd_band', ...
    'band_low_hz','band_high_hz','realized_band_low_hz', ...
    'realized_band_high_hz','realized_bin_count','psd_density_unit', ...
    'psd_band_energy_unit','healthy_rms','intervention_rms','delta_rms', ...
    'healthy_abs_peak','intervention_abs_peak','delta_abs_peak', ...
    'healthy_psd_band_energy', ...
    'intervention_psd_band_energy','delta_psd_band_energy'});
end

