# ===== STAGE selector — mirrors scour_MATLAB/A00_Run.m's STAGE preset =====
# Pick the stage whose dataset you generated with A00. Each sets the dataset
# folder, the scour targets, and whether bearing heads are added. The DATASET
# names follow A00's case_name convention; VERIFY the exact folder name (esp.
# the states<N> count) against what landed in data/ before a long run.
STAGE = "stage1_bearing"   # stage0_multiscour | stage1_bearing | stage2_4span

if STAGE == "stage0_multiscour":
    DATASET         = "L60_3span_multi_scour_scourS2-3_bearOFF_dano0-60pct_states259_Npass50_varNVST"
    TARGET_SUPPORTS = [2, 3]
    BEARING_TARGETS = None
elif STAGE == "stage1_bearing":
    # A00 STAGE='stage1_bearing' -> bearTGT; 17 anchors + 250 LHS = 267 states.
    DATASET         = "L60_3span_multi_scour_scourS2-3_bearTGT_dano0-60pct_states267_Npass50_varNVST"
    TARGET_SUPPORTS = [2, 3]
    BEARING_TARGETS = ["left", "right"]
elif STAGE == "stage2_4span":
    # A00 STAGE='stage2_4span' -> L100/4-span, internal piers 2,3,4 + bearing.
    DATASET         = "L100_4span_multi_scour_scourS2-3-4_bearTGT_..._Npass50_varNVST"  # CONFIRM
    TARGET_SUPPORTS = [2, 3, 4]
    BEARING_TARGETS = ["left", "right"]
else:
    raise ValueError(f"unknown STAGE {STAGE!r}")

# Bearing heads (Stage 1+): laid out AFTER the scour heads, reported separately
# (scour_mse vs bearing_mse) + a leakage/disentanglement report; localisation
# stays on the scour heads. None = scour-only (Stage 0, byte-identical).

TASK           = "regression"
DISCRETIZATION = 1            # kept for cache/scaler naming consistency (unused by the heads)
N_TRIALS       = 75           # lighter HPO than the single-scour 200
EPOCHS         = 50
OPTUNA_SEED    = 42           # single seed - no multi-seed Monte-Carlo for the reduced grid
ALL_DOFS       = list(range(8))

# Best pair. Leave None to auto-select the two best single sensors from Phase 1
# (lowest PAA+N-HiTS aggregate MSE). Set explicitly (e.g. [2, 5]) to override.
PAIR_DOFS = None

# Where the leaderboard + parity/leakage plots are written (stage-tagged).
SUMMARY_DIR = os.path.join("results", f"{STAGE}_summary")

ARCHITECTURES = [
    {"name_short": "PAA_NHiTS",     "method": "PAA",
     "use_space2vec": False, "use_lstm": False, "use_nhits": True,
     "model_type": "1D_MODULAR"},
    {"name_short": "PAA_S2V_NHiTS", "method": "PAA",
     "use_space2vec": True,  "use_lstm": False, "use_nhits": True,
     "model_type": "1D_MODULAR"},
    # Only if Space2Vec does NOT help, uncomment the LSTM arm:
    # {"name_short": "PAA_LSTM_NHiTS", "method": "PAA",
    #  "use_space2vec": False, "use_lstm": True, "use_nhits": True,
    #  "model_type": "1D_MODULAR"},
]

# The champion backbone used to RANK single sensors for the auto-pair.
RANK_ARCH = "PAA_NHiTS"

# Records every phase that ran so the summary can re-evaluate each champion.
_RAN_PHASES: list[dict] = []


# =============================================================================
#  Config / phase helpers
# =============================================================================
def make_config(arch: dict, dofs: list[int]) -> dict:
    """One experiment_path entry - a multi-output REGRESSION config."""
    dof_str = "_".join(str(d) for d in dofs)
    return {
        "name":            f"{arch['name_short']}_DOFs_{dof_str}_seed{OPTUNA_SEED}",
        "name_short":      arch["name_short"],
        "method":          arch["method"],
        "dofs":            list(dofs),
        "discretization":  DISCRETIZATION,
        "use_space2vec":   arch["use_space2vec"],
        "use_lstm":        arch["use_lstm"],
        "use_nhits":       arch["use_nhits"],
        "model_type":      arch["model_type"],
        # --- the multi-output regression switch (core/task.py) ---
        "task":            TASK,
        "target_supports": TARGET_SUPPORTS,
        "bearing_targets": BEARING_TARGETS,   # None for Stage 0
    }


def run_phase(phase_label: str, dofs: list[int]) -> None:
    """Run every architecture on one DOF subset (single Optuna seed, no MC)."""
    configs = [make_config(arch, dofs) for arch in ARCHITECTURES]
    db, out, cache = define_save_locations(
        phase_label, dataset=DATASET, DOFs=dofs, discretization=DISCRETIZATION,
    )
    print(f"\n{'#' * 64}\n#  {phase_label}   DOFs={dofs}   targets={TARGET_SUPPORTS}\n"
          f"#  archs: {[a['name_short'] for a in ARCHITECTURES]}\n{'#' * 64}")
    execute_ablation_pipeline(
        experiment_path = configs,
        database_name   = db,
        output_dir_name = out,
        cache_dir_name  = cache,
        dataset         = DATASET,
        n_trials        = N_TRIALS,
        epochs          = EPOCHS,
        optuna_seed     = OPTUNA_SEED,
        use_pruner      = True,
        run_robustness  = False,     # reduced grid: single seed, no 30-seed MC
    )
    _RAN_PHASES.append({"phase_label": phase_label, "dofs": list(dofs),
                        "configs": configs, "db": db,
                        "output_dir": out, "cache_dir": cache})


def phase_1_single_dof() -> None:
    print("\n" + "=" * 64 + "\n  STAGE 0 - PHASE 1 - single-DOF sweep\n" + "=" * 64)
    for dof in ALL_DOFS:
        run_phase(f"MD0_SingleDOF_{IDX_TO_DOF_NAME[dof]}", [dof])


def auto_select_pair() -> list[int]:
    """Two best single sensors by RANK_ARCH aggregate MSE from Phase 1 studies."""
    if PAIR_DOFS:
        print(f"\n[pair] using user-set PAIR_DOFS = {PAIR_DOFS}")
        return list(PAIR_DOFS)

    scores: list[tuple[float, int]] = []
    for dof in ALL_DOFS:
        phase_label = f"MD0_SingleDOF_{IDX_TO_DOF_NAME[dof]}"
        db, _, _ = define_save_locations(phase_label, DATASET, [dof], DISCRETIZATION)
        study_name = f"{RANK_ARCH}_DOFs_{dof}_seed{OPTUNA_SEED}"
        try:
            study = optuna.load_study(study_name=study_name, storage=db)
            scores.append((study.best_value, dof))
        except Exception as e:                               # noqa: BLE001
            print(f"  [pair] skip DOF {dof} ({IDX_TO_DOF_NAME[dof]}): {e}")

    if len(scores) < 2:
        raise RuntimeError("auto-pair needs >=2 completed single-DOF studies.")
    scores.sort(key=lambda t: t[0])
    print("\n[pair] single-sensor ranking (aggregate MSE, %^2, lower=better):")
    for mse, dof in scores:
        print(f"        {IDX_TO_DOF_NAME[dof]:<18} DOF {dof}   MSE {mse:.3f}")
    best = sorted(dof for _, dof in scores[:2])
    print(f"[pair] -> best two sensors: {[IDX_TO_DOF_NAME[d] for d in best]}  (DOFs {best})")
    return best


def phase_2_pair(pair: list[int]) -> None:
    a, b = (IDX_TO_DOF_NAME[i] for i in pair)
    print("\n" + "=" * 64 + f"\n  STAGE 0 - PHASE 2 - best pair {a} + {b}\n" + "=" * 64)
    run_phase(f"MD0_Pair_{a}__{b}", list(pair))


# =============================================================================
