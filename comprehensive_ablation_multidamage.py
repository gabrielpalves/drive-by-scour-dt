    """Authenticate the block-local champion and HPO manifest for a follower."""

    global _manifest, _CHAMPION_EXECUTION_STATUS
    global CHAMPION_ARCH, CHAMPION_PAIR, RANK_ARCH, ARCHITECTURES
    global _HYPERPARAMETER_MANIFEST, _HYPERPARAMETER_MANIFEST_SHA256

    if STAGE in ARCH_SELECTION_STAGES:
        raise RuntimeError("block anchors do not load a prior reference")
