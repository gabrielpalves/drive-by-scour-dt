def _load_block_reference_manifest() -> dict | None:
    """Load and content-authenticate this block's independent reference."""

    if not os.path.lexists(CHAMPION_MANIFEST):
        return None
    try:
        manifest = _parse_json_object_snapshot(
            Path(CHAMPION_MANIFEST), "block reference manifest"
        )
    except RuntimeError as exc:
        raise SystemExit(
            f"{STAGE}: reference manifest is unreadable or malformed: "
            f"{CHAMPION_MANIFEST}") from exc

    actual_reference_sha = hyperparameter_json_sha256(manifest)
    if (
        not BLOCK_REFERENCE_SHA256
        or actual_reference_sha != BLOCK_REFERENCE_SHA256
    ):
        raise SystemExit(
            f"{STAGE}: reference manifest canonical SHA-256 "
            f"{actual_reference_sha!r} differs from the independently supplied "
            "TTBI_BLOCK_REFERENCE_SHA256. Refusing a mutable selection path."
        )
    if set(manifest) != BLOCK_REFERENCE_MANIFEST_FIELDS:
        raise SystemExit(
            f"{STAGE}: reference fields differ from the exact contract; "
            "missing="
            f"{sorted(BLOCK_REFERENCE_MANIFEST_FIELDS - set(manifest))}, "
            "extra="
            f"{sorted(set(manifest) - BLOCK_REFERENCE_MANIFEST_FIELDS)}."
        )
    if manifest["schema"] != SCHEMA_TAG:
        raise SystemExit(
            f"{STAGE}: reference schema {manifest['schema']!r} differs from "
            f"{SCHEMA_TAG!r}.")

    block, anchor = execution_block_for_stage(STAGE, EXECUTION_BLOCK_POLICY)
    anchor_dataset = _LADDER[anchor][0]
    if (
        _EXECUTION_ATTESTATION is None
        or _CAPACITY_PREFLIGHT_RECEIPT is None
    ):
        raise SystemExit(
            f"{STAGE}: cannot authenticate a block reference before the "
            "execution and capacity receipts exist."
        )
    # The independently retained TTBI_BLOCK_REFERENCE_SHA256 authenticates the
    # complete object.  The HPO-manifest and anchor-protocol digests below may
    # therefore be read from that pinned object now; _initialize_follower_reference
    # subsequently authenticates the referenced HPO file and cross-checks its
    # anchor protocol.  All shape/type/selection semantics live in the shared
    # validator used by both execution and offline inference.
    try:
        manifest = validate_block_reference_manifest(
            manifest,
            expected_anchor_stage=anchor,
            expected_dataset=anchor_dataset,
            expected_schema=SCHEMA_TAG,
            expected_run_tag=RUN_TAG,
            expected_seeds=SEEDS,
            expected_anchor_n_trials=N_TRIALS,
            expected_candidate_n_trials=HYPERPARAMETER_POLICY[
                "frozen_singleton"
            ]["n_trials"],
            expected_protocol_core_hash=PROTOCOL_CORE_HASH,
            expected_anchor_protocol_hash=manifest["protocol_hash"],
            expected_execution_runtime=
                _EXECUTION_ATTESTATION["runtime"],
            expected_execution_receipt_sha256=
                _EXECUTION_ATTESTATION["receipt_sha256"],
            expected_hyperparameter_manifest_sha256=
                manifest["hyperparameter_manifest_sha256"],
            expected_hyperparameter_policy_sha256=
                hyperparameter_policy_sha256(),
            valid_architectures=tuple(
                architecture["name_short"]
                for architecture in ALL_ARCHITECTURES
            ),
            valid_dofs=tuple(ALL_DOFS),
        )
        validate_execution_runtime(manifest["execution_runtime"])
    except RuntimeError as exc:
        raise SystemExit(
            f"{STAGE}: invalid block-reference contract: {exc}") from exc
    capacity_sha = manifest["capacity_preflight_receipt_sha256"]
    if capacity_sha != _CAPACITY_PREFLIGHT_RECEIPT.get("receipt_sha256"):
        raise SystemExit(
            f"{STAGE}: reference is not an authenticated {block}/{anchor} "
            "block-anchor selection with the current capacity receipt.")
    return manifest


def _validate_pair(dofs, src: str) -> list[int]:
    """Two DISTINCT valid DOFs (audit R7.1 P3: reject [1,1] etc.)."""
    if (
        not isinstance(dofs, (list, tuple))
        or any(isinstance(value, bool) or not isinstance(value, int)
               for value in dofs)
    ):
        raise SystemExit(
            f"{src} must contain exactly two integer DOF indices."
        )
    dofs = sorted(dofs)
    if len(dofs) != 2 or len(set(dofs)) != 2 or any(d not in ALL_DOFS for d in dofs):
        raise SystemExit(f"{src} = {dofs} must be TWO DISTINCT valid DOFs from "
                         f"{ALL_DOFS} (got a duplicate or invalid index).")
    return dofs


def _frozen_selection_sha256_for_reference(
    architecture: str,
    champion_pair: list[int],
) -> str:
    """Authenticate the anchor selection artifact linked by the reference."""

    path = os.path.join(SUMMARY_DIR, "frozen_selection.json")
    try:
        frozen = _parse_json_object_snapshot(
            Path(path), "anchor frozen selection"
        )
    except RuntimeError as exc:
        raise RuntimeError(
            "anchor frozen selection is unreadable or malformed"
        ) from exc
    expected_fields = {
        "stage",
        "architecture",
        "dofs",
        "selected_pair",
        "inner_val_mse",
        "selection_metric",
        "deployment_selection",
        "protocol_hash",
        "protocol_core_hash",
        "execution_runtime",
        "execution_environment_sha256",
        "execution_receipt_sha256",
        "capacity_preflight_receipt_sha256",
        "hyperparameter_mode",
        "campaign_run_tag",
        "block_reference_manifest_sha256",
        "hyperparameter_manifest_sha256",
        "hyperparameter_source_json",
        "pre_registered_comparators",
    }
    if set(frozen) != expected_fields:
        raise RuntimeError(
            "anchor frozen selection fields differ from the exact contract"
        )
    try:
        frozen_pair = _validate_pair(
            frozen["selected_pair"], "frozen selected_pair"
        )
        expected_pair = _validate_pair(
            champion_pair, "reference champion_pair"
        )
        frozen_runtime = validate_execution_runtime(
            frozen["execution_runtime"]
        )
        source = json.loads(frozen["hyperparameter_source_json"])
        canonical_source = json.dumps(
            source,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=True,
            allow_nan=False,
        )
    except (KeyError, TypeError, ValueError, RuntimeError, SystemExit) as exc:
        raise RuntimeError(
            "anchor frozen selection lacks a valid pair/runtime binding"
        ) from exc
    inner_value = frozen["inner_val_mse"]
    comparators = frozen["pre_registered_comparators"]
    expected_dofs = "+".join(
        IDX_TO_DOF_NAME[value] for value in frozen_pair
    )
    if (
        _EXECUTION_ATTESTATION is None
        or _CAPACITY_PREFLIGHT_RECEIPT is None
        or _HYPERPARAMETER_MANIFEST_SHA256 is None
        or frozen.get("stage") != STAGE
        or frozen.get("architecture") != architecture
        or frozen_pair != expected_pair
        or frozen.get("dofs") != expected_dofs
        or isinstance(inner_value, bool)
        or not isinstance(inner_value, (int, float))
        or not math.isfinite(float(inner_value))
        or float(inner_value) < 0.0
        or not isinstance(frozen.get("deployment_selection"), bool)
        or frozen["deployment_selection"]
            is not (STAGE in DEPLOYMENT_SELECTION_STAGES)
        or frozen.get("protocol_hash") != PROTOCOL_HASH
        or frozen.get("protocol_core_hash") != PROTOCOL_CORE_HASH
        or frozen_runtime != _EXECUTION_ATTESTATION["runtime"]
        or frozen.get("execution_environment_sha256")
            != frozen_runtime["execution_environment_sha256"]
        or frozen.get("execution_receipt_sha256")
            != _EXECUTION_ATTESTATION["receipt_sha256"]
        or frozen.get("capacity_preflight_receipt_sha256")
            != _CAPACITY_PREFLIGHT_RECEIPT["receipt_sha256"]
        or frozen.get("hyperparameter_manifest_sha256")
            != _HYPERPARAMETER_MANIFEST_SHA256
        or frozen.get("hyperparameter_mode") != FROZEN_SINGLETON_MODE
        or frozen.get("campaign_run_tag") != RUN_TAG
        or frozen.get("block_reference_manifest_sha256") is not None
        or not isinstance(source, dict)
        or frozen["hyperparameter_source_json"] != canonical_source
        or not isinstance(comparators, list)
        or not comparators
        or any(not isinstance(value, str) or not value
               for value in comparators)
        or len(comparators) != len(set(comparators))
        or f"{architecture} on {expected_dofs}" not in comparators
        or frozen.get("selection_metric") != TRAIN_PROTOCOL["objective"]
    ):
        raise RuntimeError(
            "anchor frozen selection does not reproduce the completed "
            "architecture/pair selection and authenticated runtime"
        )
    return hyperparameter_json_sha256(frozen)


