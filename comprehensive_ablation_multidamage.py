def _test_loader(config: dict, cache_dir: str):
    """Loader over the UNTOUCHED outer TEST set (audit R5). Everything the model
    saw during fit/HPO/selection was train+inner-val; the summary reports here so
    the paper's numbers come from a set that never influenced model choice.

    Also returns the per-sample STATE ids of the test set (Feature A) so the
    disentanglement probe can look samples up by family IDENTITY, not by
    thresholding labels."""
    X, y, _, groups = get_or_create_cache(config, DATASET, cache_dir)
    test_idx = canonical_test_split(len(y), groups, dataset_name=DATASET)
    if len(test_idx) == 0:                 # legacy classification (no test set)
        _, test_idx = canonical_train_val_split(len(y), groups,
                                                dataset_name=DATASET)
    loader = DataLoader(
        MemmapDataset(X, y, test_idx, label_dtype=task.label_dtype(config)),
        batch_size=64, shuffle=False,
    )
    test_states = (np.asarray(groups)[test_idx] if groups is not None else None)
    return loader, X.shape, test_states


def _inner_val_of(cfg: dict, db: str) -> float | None:
    """study.best_value (best INNER-VAL MSE) for a config, but ONLY if its study is
    finished (audit R7 P1/P2). Returns None otherwise. Touches NO test data."""
    try:
        study = optuna.load_study(study_name=cfg["name"], storage=db)
    except Exception as e:                                   # noqa: BLE001
        print(f"  [summary] cannot load study {cfg['name']}: {e}")
        return None
    if not _study_is_finished(study, N_TRIALS):
        print(f"  [summary] study {cfg['name']} NOT finished - excluded.")
        return None
    return float(study.best_value)


def evaluate_champion(config: dict, db: str, output_dir: str, cache_dir: str) -> dict | None:
    """Load a config's champion weights and return its OUTER-TEST metrics — ONLY if
    the study is FINISHED and weights exist (audit R7 P1). Called for the frozen
    winner + pre-registered comparators only, after selection is frozen.
    Returns private per-state errors for the hierarchical cross-seed inference;
    it deliberately does not construct invalid per-seed confidence bounds."""
    weights = os.path.join(output_dir, config["name"], "DT_champion_weights.pth")
    if not os.path.exists(weights):
        print(f"  [summary] no champion weights for {config['name']} - skipped.")
        return None
    try:
        study = optuna.load_study(study_name=config["name"], storage=db)
    except Exception as e:                                   # noqa: BLE001
        print(f"  [summary] cannot load study {config['name']}: {e}")
        return None
    if not _study_is_finished(study, N_TRIALS):
        print(f"  [summary] study {config['name']} NOT finished - not reported.")
        return None
    verify_digital_twin_package(study, config, os.path.dirname(weights))
    loader, shape, test_states = _test_loader(config, cache_dir)
    model, _ = build_model(config, study.best_params, shape, DEVICE)
    model.load_state_dict(torch.load(weights, map_location=DEVICE))
    m = task.evaluate(model, loader, config, DEVICE)
    m["inner_val_mse"] = float(study.best_value)
    # State-level errors (regression + grouped data only). One extra forward
    # pass over the small test set is negligible next to training.
    if test_states is not None and task.is_regression(config):
        model.eval()
        preds, trues = [], []
        with torch.no_grad():
            for bx, by in loader:
                preds.append(model(bx.to(DEVICE)).cpu().numpy())
                trues.append(by.numpy())
        state_m = per_state_regression_metrics(
            np.vstack(preds), np.vstack(trues), np.asarray(test_states),
            n_scour_heads=len(TARGET_SUPPORTS),
        )
        m["_state_ids"] = state_m["state"]
        m["_state_scour_mse"] = state_m["scour_mse"]
        m["_state_all_head_mse"] = state_m["all_head_mse"]
        m["_state_predicted_max_scour_pct"] = \
            state_m["predicted_max_scour_pct"]
    return m


def _metrics_row(ph: dict, cfg: dict, m: dict) -> dict:
    """One reported row: OUTER-TEST metrics + the inner-val objective."""
    n_s = len(TARGET_SUPPORTS)
    bt = cfg.get("bearing_targets") or []
    head_cols = {}
    for i, v in enumerate(m.get("per_head_mse", [])):
        if i < n_s:
            head_cols[f"mse_support_{TARGET_SUPPORTS[i]}"] = round(v, 4)
        else:
            bname = bt[i - n_s] if (i - n_s) < len(bt) else (i - n_s)
            head_cols[f"mse_bearing_{bname}"] = round(v, 4)
    row = {
        "phase": ph["phase_label"], "architecture": cfg["name_short"],
        "dofs": "+".join(IDX_TO_DOF_NAME[d] for d in cfg["dofs"]),
        "seed": cfg.get("seed", SEEDS[0]), "n_sensors": len(cfg["dofs"]),
        "inner_val_mse": round(m["inner_val_mse"], 4),
        "agg_mse": round(m["mse"], 4), "agg_mae": round(m["mae"], 4),
        "localisation_acc": (round(m["primary"], 4)
                             if m["primary"] == m["primary"] else "nan"),
    }
    row["scour_mse"] = round(m.get("scour_mse", m["mse"]), 4)
    if "bearing_mse" in m:
        row["bearing_mse"] = round(m["bearing_mse"], 4)
    row.update(head_cols)
    return row


def _write_rows_csv(path: str, rows: list[dict]) -> None:
    fields = list(dict.fromkeys(k for r in rows for k in r))
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def _write_json_atomic(path: str, obj) -> None:
    """Atomic JSON write (temp + os.replace) — audit R7 P2/P3."""
    tmp = path + ".tmp"
    with open(tmp, "w") as fh:
        json.dump(obj, fh, indent=2)
    os.replace(tmp, path)


def summarize() -> tuple[list[int], str]:
    """STRICT select-then-report protocol (audit R7 P2 / R4 statistics).
    The outer-TEST reporting phase cannot begin until selection is frozen,
    finalist CV has finished, and every comparator passes preflight. It contains
    only the winner + pre-registered comparators; downstream plots/probes may
    stream that same held set again but can never tune or re-select from it:
      (1) build the leaderboard from INNER-VALIDATION only (study.best_value) —
          no test data opened here;
      (2) validate study + pair-matrix completeness;
      (3) SELECT the winner on inner-val and FREEZE it (returned to the driver,
          which writes the manifest);
      (4) repeated grouped CV for finalists on development states only;
      (5) evaluate TEST only for the winner + the pre-registered finalist and
          control set (top-K joint candidates, each architecture's own best
          placement, carried/designed pairs and full-array controls);
      (6) report those + parity + disentanglement on that same held set.
    Returns the selected best-PAIR DOFs, or None if no pair ran.
    """
    os.makedirs(SUMMARY_DIR, exist_ok=True)
    print("\n" + "=" * 64 + f"\n  {STAGE} - RESULTS SUMMARY\n" + "=" * 64)

    # ── (1) INNER-VALIDATION leaderboard — NO test touched ───────────────────
    iv_rows: list[dict] = []
    for ph in _RAN_PHASES:
        for cfg in ph["configs"]:
            iv = _inner_val_of(cfg, ph["db"])
            if iv is None:
                continue
            iv_rows.append({
                "phase": ph["phase_label"], "architecture": cfg["name_short"],
                "dofs": "+".join(IDX_TO_DOF_NAME[d] for d in cfg["dofs"]),
                "seed": cfg.get("seed", SEEDS[0]), "n_sensors": len(cfg["dofs"]),
                # FULL precision (audit R7.1 P3): rounding to 4 dp before selection
                # could flip near-tied candidates. Rounded only for display later.
                "inner_val_mse": float(iv),
            })
    if not iv_rows:
        raise RuntimeError(
            f"{STAGE}: NO finished studies to summarise — every study failed to "
            f"reach the useful budget (or none ran). This is fatal at ANY rung; "
            f"do not proceed to selection/reporting.")
    iv_rows.sort(key=lambda r: r["inner_val_mse"])
    _write_rows_csv(os.path.join(SUMMARY_DIR, "leaderboard_innerval.csv"), iv_rows)
    print(f"  Inner-val leaderboard ({len(iv_rows)} finished models — the SELECTION "
          f"basis) -> {os.path.join(SUMMARY_DIR, 'leaderboard_innerval.csv')}")
    iv_agg = _median_leaderboard(iv_rows, "leaderboard_innerval_median.csv")

    # ── (2)+(3) SELECT the winner on inner-val + completeness gate ───────────
    # EVERY stage runs a pair phase (search or frozen); NO singleton fallback
    # (audit R7.1 P1) — a stage with no finished pair is a hard error, never a
    # champion published on a singleton with champion_pair=None.
    pair_rows = [r for r in iv_agg if r.get("n_sensors") == 2]
    if not pair_rows:
        raise RuntimeError(
            f"{STAGE}: NO finished pair studies — cannot select/report a pair "
            f"(the pair phase did not complete). Do not publish a champion.")
    _assert_pair_matrix_complete(pair_rows)
    selected_pair = None
    if STAGE in PAIR_SEARCH_STAGES:
        win = min(pair_rows, key=lambda r: r["inner_val_mse"])
        _, win_cfg = _find_cfg(win)
        if win_cfg is None:
            raise RuntimeError(
                f"{STAGE}: winner pair {win['dofs']} could not be resolved to a "
                f"config — internal error; refusing to publish.")
        selected_pair = list(win_cfg["dofs"])
        print(f"  BEST PAIR (SELECTED by median INNER-VAL MSE): "
              f"{win['architecture']} on {win['dofs']}  "
              f"inner_val={win['inner_val_mse']:.6g} "
              f"(IQR {win.get('inner_val_mse_iqr', 'n/a')})")
    else:
        frozen_str = "+".join(IDX_TO_DOF_NAME[d] for d in CHAMPION_PAIR)
        win = next((r for r in pair_rows if r["dofs"] == frozen_str), None)
        if win is None:
            raise RuntimeError(
                f"frozen pair {frozen_str} is not among the FINISHED pair studies "
                f"at {STAGE} — its studies did not complete; cannot report the "
                f"ladder point.")
        selected_pair = list(CHAMPION_PAIR)
        print(f"  FROZEN PAIR (carried from s0): {win['architecture']} on "
              f"{win['dofs']}  inner_val={win['inner_val_mse']:.6g}")

    # ── (4) PRE-REGISTERED comparator set (declared BEFORE any test touch) ────
    # Feature B (2026-07-19): comparators are keyed by (ARCHITECTURE, pair) —
    # at single-arch rungs this reduces to the old pair keying; at deployment
    # rungs it distinguishes the same pair under different arms.
    comparators: set = set()
    _, win_cfg = _find_cfg(win)
    if win_cfg:
        comparators.add((win["architecture"], tuple(sorted(win_cfg["dofs"]))))
    # The carried s0 champion combo = the ladder-continuity point. At a
    # deployment rung this is exactly the (arch, pair) the ladder would deploy,
    # so the deployment claim is reported AGAINST it.
    if CHAMPION_ARCH and CHAMPION_PAIR:
        comparators.add((CHAMPION_ARCH, tuple(sorted(CHAMPION_PAIR))))
    for xp in EXTRA_PAIRS:
        # Same-architecture placement contrast for the selected joint winner.
        # At later rungs retain the carried s0 arm too, if it differs.
        extra_arches = {win["architecture"]}
        if CHAMPION_ARCH:
            extra_arches.add(CHAMPION_ARCH)
        for arch in extra_arches:
            comparators.add((arch, tuple(sorted(int(d) for d in xp))))
    # At a full architecture x pair stage, compare all architectures on the
    # exact selected pair and on the exact full-array control.  This closes the
    # architecture/sensor interaction gap while keeping the remaining candidate
    # grid sealed away from the outer test.
    comparators.update(_same_pair_architecture_keys(selected_pair))
    comparators.update(_control_comparator_keys(win["architecture"]))
    if STAGE in FINALIST_CV_STAGES:
        # Genuine finalist set: the closest joint runners-up and every
        # architecture evaluated at its own best placement. Without this, CV
        # could compare all architectures only at a winner-favoured pair and
        # miss the actual near-tied placement competitors.
        ranked_pairs = sorted(pair_rows, key=lambda row: row["inner_val_mse"])
        finalist_rows = list(ranked_pairs[:FINALIST_TOP_K])
        for arch in sorted({row["architecture"] for row in pair_rows}):
            finalist_rows.append(min(
                (row for row in pair_rows if row["architecture"] == arch),
                key=lambda row: row["inner_val_mse"],
            ))
        for row in finalist_rows:
            _ph, cfg = _find_cfg(row)
            if cfg is None:
                raise RuntimeError(
                    f"cannot resolve pre-registered finalist {row}")
            comparators.add((
                row["architecture"],
                tuple(sorted(int(d) for d in cfg["dofs"])),
            ))

    def _ckey_str(c):                        # ('ARCH', (d0, d1)) -> readable
        return f"{c[0]} on " + "+".join(IDX_TO_DOF_NAME[d] for d in c[1])

    # FREEZE the selection to disk BEFORE any test touch (audit R7 P2): an
    # auditable record that the winner + comparator set were fixed on inner-val,
    # independent of the test numbers computed next.
    _write_json_atomic(
        os.path.join(SUMMARY_DIR, "frozen_selection.json"),
        {"stage": STAGE, "architecture": win["architecture"], "dofs": win["dofs"],
         "selected_pair": selected_pair,
         "inner_val_mse": win.get("inner_val_mse"),
         "selection_metric": "median_inner_val_mse (scour-primary objective)",
         "deployment_selection": STAGE in DEPLOYMENT_SELECTION_STAGES,
         # Unified protocol hash (2026-07-19): binds this frozen selection to
         # the exact protocol (and dataset fingerprint) it was made under.
         "protocol_hash": PROTOCOL_HASH,
         "protocol_core_hash": PROTOCOL_CORE_HASH,
         "pre_registered_comparators": [_ckey_str(c) for c in sorted(comparators)]})
    # PREFLIGHT (audit R7.1 P4): confirm every comparator has all SEEDS finished +
    # weighted BEFORE opening the test set — never touch test on a partial set.
    _preflight_comparators(comparators)
    winner_key = (
        win["architecture"], tuple(sorted(int(d) for d in win_cfg["dofs"]))
    )
    # The robustness analysis is deliberately placed HERE: selection is frozen
    # and every finalist passed preflight, while no test loader has been called.
    if STAGE in FINALIST_CV_STAGES:
        _run_finalist_repeated_cv(comparators, winner_key)
    else:
        print(
            f"  Finalist repeated CV skipped by pre-registered policy at {STAGE}: "
            "this rung carries a frozen pair and performs no grid selection."
        )
    print("  Opening the OUTER TEST reporting phase, only for the frozen winner + "
          "pre-registered comparators (no tuning/re-selection from this point): "
          + str([_ckey_str(c) for c in sorted(comparators)]))

    # ── (4b) TEST — winner + comparators ONLY, requiring the FULL seed set ────
    reported: list[dict] = []
    test_state_rows: list[dict] = []
    test_state_table = read_state_table(os.path.join("data", DATASET))
    for ph in _RAN_PHASES:
        for cfg in ph["configs"]:
            if (cfg["name_short"], tuple(sorted(cfg["dofs"]))) not in comparators:
                continue
            m = evaluate_champion(cfg, ph["db"], ph["output_dir"], ph["cache_dir"])
            if m:
                reported.append(_metrics_row(ph, cfg, m))
                if "_state_ids" in m:
                    dofs_label = _dofs_label(cfg["dofs"])
                    for i, state in enumerate(m["_state_ids"].astype(int)):
                        test_state_rows.append({
                            "architecture": cfg["name_short"],
                            "dofs": dofs_label,
                            "seed": int(cfg.get("seed", SEEDS[0])),
                            "repeat": 0,
                            "state": int(state),
                            "family": str(test_state_table["family"][state]),
                            "scour_mse": float(m["_state_scour_mse"][i]),
                            "all_head_mse":
                                float(m["_state_all_head_mse"][i]),
                            "predicted_max_scour_pct": float(
                                m["_state_predicted_max_scour_pct"][i]
                            ),
                        })
    # Every reported (arch, pair) comparator must have EXACTLY len(SEEDS)
    # finished test rows (audit R7.1 P1) — a missing weight or a short seed set
    # must be a hard error, not a silent drop from the published table.
    _assert_reported_complete(reported, comparators)
    test_agg = []
    if reported:
        reported.sort(key=lambda r: r.get("inner_val_mse", float("inf")))
        _write_rows_csv(os.path.join(SUMMARY_DIR, "leaderboard_test.csv"), reported)
        print(f"  Reported OUTER-TEST leaderboard ({len(reported)} models: winner + "
              f"comparators) -> {os.path.join(SUMMARY_DIR, 'leaderboard_test.csv')}")
        test_agg = _median_leaderboard(reported, "leaderboard_test_median.csv")
        # Construct joint state x 1 x seed tensors only after every finalist's
        # per-state record exists. This replaces the invalid median of separate
        # per-seed CI endpoints and produces paired state-level contrasts.
        test_agg = _outer_test_hierarchical_inference(
            test_state_rows, comparators, winner_key, test_agg
        )
        _write_rows_csv(
            os.path.join(SUMMARY_DIR, "leaderboard_test_median.csv"), test_agg
        )
        _write_rows_csv(
            os.path.join(SUMMARY_DIR, "outer_test_state_metrics.csv"),
            test_state_rows,
        )
    else:
        print("  [summary] winner/comparator weights missing — TEST not evaluated.")

    # ── (5) headline (winner's median TEST) + parity + disentanglement ───────
    win_test = next((r for r in test_agg
                     if r["architecture"] == win["architecture"]
                     and r["dofs"] == win["dofs"]), None)
    if win_test:
        print(f"    -> reported OUTER-TEST primary scour_MSE="
              f"{win_test.get('scour_mse')} "
              f"(state-first CI95 "
              f"[{win_test.get('scour_mse_ci95_lo', 'n/a')}, "
              f"{win_test.get('scour_mse_ci95_hi', 'n/a')}], "
              f"{win_test.get('n_seeds', '?')} seeds)  "
              f"loc_acc={win_test.get('localisation_acc')}")
    # ── (5b) Feature B: SEPARATE deployment manifest at deployment rungs ─────
    # Records the exploratory (arch, pair) winner + its precise CLAIM. Never
    # touches the s0 champion manifest and no later rung reads this file.
    if STAGE in DEPLOYMENT_SELECTION_STAGES:
        dep_path = os.path.join(
            "results", _with_run_tag(
                f"_deployment_selection_{STAGE}_{SCHEMA_TAG}"
                f"_ph-{PROTOCOL_HASH_SHORT}") + ".json")
        arch_names = sorted(a["name_short"] for a in ARCHITECTURES)
        _write_json_atomic(dep_path, {
            "selection_kind": "deployment (exploratory — does NOT replace the "
                              "s0 ladder champion)",
            "stage": STAGE, "dataset": DATASET, "schema": SCHEMA_TAG,
            "run_tag": RUN_TAG,
            "protocol_hash": PROTOCOL_HASH,
            "protocol_core_hash": PROTOCOL_CORE_HASH,
            "seeds": list(SEEDS), "n_trials": N_TRIALS,
            "winner": {"architecture": win["architecture"],
                       "pair": selected_pair,
                       "inner_val_mse_median": win.get("inner_val_mse"),
                       "test_scour_mse_median": (win_test or {}).get("scour_mse"),
                       "test_scour_mse_ci95": [
                           (win_test or {}).get("scour_mse_ci95_lo"),
                           (win_test or {}).get("scour_mse_ci95_hi")],
                       "test_agg_mse_median": (win_test or {}).get("agg_mse"),
                       "test_agg_mse_ci95": [(win_test or {}).get("agg_mse_ci95_lo"),
                                             (win_test or {}).get("agg_mse_ci95_hi")]},
            "carried_s0_champion": {"architecture": CHAMPION_ARCH,
                                    "pair": list(CHAMPION_PAIR) if CHAMPION_PAIR else None},
            # The EXACT claim this selection supports — quote it, no more:
            "claim": (f"best among architectures {arch_names} x C(8,2)=28 "
                      f"two-sensor pairs, at {N_TRIALS} Optuna trials x "
                      f"{len(SEEDS)} seeds, on {DATASET} (this budget and "
                      f"geometry). NOT a best-sensor-COUNT claim and NOT a "
                      f"global optimum."),
        })
        print(f"  [deployment] wrote {dep_path}  -> "
              f"{win['architecture']} on {selected_pair} (exploratory; s0 "
              f"champion untouched)")
    _parity_plot_for_best(win_test or win)
    if BEARING_TARGETS and reported:
        disentanglement_report(reported)
    return selected_pair, win["architecture"]


def _assert_pair_matrix_complete(pair_rows: list[dict]) -> None:
    """The best-pair claim requires the FULL pair matrix (audit R6 C8A), mirroring
    _pick_champion_arch's arch-matrix guard. Every (arch, pair) config must have
    all SEEDS, and — under EXHAUSTIVE_PAIRS — all C(8,2)=28 pairs must be present
    PER ARCHITECTURE RUNNING AT THIS STAGE (Feature B: a deployment rung runs
    all four arms, so its matrix is 28 x 4 median rows = 336 pair studies).
    Without
    this, a combo backed by a single lucky seed (or a sweep missing pairs) could
    be crowned 'best'."""
    import itertools
    short_seeds = [
        (r["architecture"], r["dofs"], r.get("seed_ids"))
        for r in pair_rows
        if (r.get("n_seeds") != len(SEEDS)
            or list(r.get("seed_ids", [])) != sorted(int(s) for s in SEEDS))
    ]
    if short_seeds:
        raise RuntimeError(
            f"pair selection: these (arch, pair) combos lack the full "
            f"{len(SEEDS)}-seed matrix {short_seeds} — finish them before "
            f"declaring a best pair.")
    if EXHAUSTIVE_PAIRS:
        expected_pair_labels = {
            "+".join(IDX_TO_DOF_NAME[d] for d in pair)
            for pair in itertools.combinations(ALL_DOFS, 2)
        }
        n_pairs = len(expected_pair_labels)
        # ARCHITECTURES is rebound by the driver to the arm set actually running
        # the pair phase (1 normally; all arms at a deployment rung).
        arch_names = {a["name_short"] for a in ARCHITECTURES}
        expected = n_pairs * len(arch_names)
        if len(pair_rows) != expected:
            got = sorted((r["architecture"], r["dofs"]) for r in pair_rows)
            raise RuntimeError(
                f"pair selection: EXHAUSTIVE_PAIRS expects {n_pairs} pairs x "
                f"{len(arch_names)} arch(s) = {expected} rows but "
                f"{len(pair_rows)} were evaluated ({got[:8]}...). Finish the "
                f"full sweep before declaring a best pair.")
        # Per-arch exact-set completeness too: matching row counts with one
        # duplicated pair and one missing pair must not pass.
        for an in sorted(arch_names):
            labels = [
                r["dofs"] for r in pair_rows if r["architecture"] == an
            ]
            if (len(labels) != n_pairs
                    or set(labels) != expected_pair_labels):
                missing = sorted(expected_pair_labels - set(labels))
                extra = sorted(set(labels) - expected_pair_labels)
                raise RuntimeError(
                    f"pair selection: architecture {an} does not contain the "
                    f"exact C(8,2) pair set (rows={len(labels)}/{n_pairs}, "
                    f"missing={missing[:5]}, extra={extra[:5]}).")


def _preflight_comparators(comparators: set) -> None:
    """BEFORE the outer test is opened (audit R7.1 P4), verify that every
    comparator — keyed (ARCHITECTURE, pair), Feature B — has the EXACT set of
    SEEDS, each with a FINISHED study AND exported weights. This is a preflight:
    if anything is missing the run aborts without ever touching test."""
    for arch, dofs in sorted(comparators):
        dof_str = "+".join(IDX_TO_DOF_NAME[d] for d in dofs)
        found_seeds: list = []
        for ph in _RAN_PHASES:
            for cfg in ph["configs"]:
                if (cfg["name_short"] != arch
                        or tuple(sorted(cfg["dofs"])) != dofs):
                    continue
                weights = os.path.join(ph["output_dir"], cfg["name"],
                                       "DT_champion_weights.pth")
                try:
                    study = optuna.load_study(study_name=cfg["name"], storage=ph["db"])
                except Exception:                            # noqa: BLE001
                    study = None
                if os.path.exists(weights) and study is not None \
                        and _study_is_finished(study, N_TRIALS):
                    verify_digital_twin_package(
                        study, cfg, os.path.dirname(weights)
                    )
                    found_seeds.append(cfg.get("seed", SEEDS[0]))
        if sorted(found_seeds) != sorted(SEEDS):
            raise RuntimeError(
                f"pre-test preflight FAILED for {arch} on {dof_str}: usable "
                f"seeds {sorted(found_seeds)} != required {sorted(SEEDS)} "
                f"(missing weights / unfinished study / duplicate). Refusing to "
                f"open the outer test on an incomplete comparison.")


def _assert_reported_complete(reported: list[dict], comparators: set) -> None:
    """Post-test guard (audit R7.1 P4): every (arch, pair) comparator's reported
    rows must be EXACTLY the SEEDS set — no missing seed AND no duplicate (a
    count of 3 with a repeated seed is NOT complete)."""
    for arch, dofs in sorted(comparators):
        dof_str = "+".join(IDX_TO_DOF_NAME[d] for d in dofs)
        seeds = [r["seed"] for r in reported
                 if r["dofs"] == dof_str and r["architecture"] == arch]
        if len(seeds) != len(SEEDS) or set(seeds) != set(SEEDS):
            raise RuntimeError(
                f"reported OUTER-TEST set for {arch} on {dof_str}: seeds "
                f"{sorted(seeds)} != {sorted(SEEDS)} (missing or duplicated). "
                f"Refusing to publish an incomplete comparison.")


def _dofs_label(dofs) -> str:
    return "+".join(IDX_TO_DOF_NAME[int(d)] for d in dofs)


def _find_comparator_config(arch: str, dofs: tuple[int, ...], seed: int):
    """Resolve one frozen finalist to exactly one phase/config."""

    matches = []
    for ph in _RAN_PHASES:
        for cfg in ph["configs"]:
            if (cfg["name_short"] == arch
                    and tuple(sorted(int(d) for d in cfg["dofs"])) == dofs
                    and int(cfg.get("seed", SEEDS[0])) == int(seed)):
                matches.append((ph, cfg))
    if len(matches) != 1:
        raise RuntimeError(
            f"finalist CV expected exactly one config for {arch} on {dofs}, "
            f"seed {seed}; found {len(matches)}"
        )
    return matches[0]


def _atomic_savez(path: str, **arrays) -> None:
    tmp = path + ".tmp.npz"
    np.savez_compressed(tmp, **arrays)
    os.replace(tmp, path)


def _fit_predict_finalist_fold(
    cfg: dict,
    params: dict,
    X: np.ndarray,
    y: np.ndarray,
    groups: np.ndarray,
    fold,
    seed: int,
    n_epochs: int | None = None,
) -> dict[str, np.ndarray]:
    """Fixed-hyperparameter refit on one development-only CV fold."""

    if str(cfg.get("method", "")).lower() != "paa":
        raise RuntimeError(
            "finalist repeated CV currently requires affine-standardised PAA "
            "features; add an explicit fold-scaler implementation before using "
            f"method={cfg.get('method')!r}"
        )
    if n_epochs is None:
        n_epochs = EPOCHS
    n_epochs = int(n_epochs)
    if not (1 <= n_epochs <= EPOCHS):
        raise ValueError(
            f"finalist-CV refit epochs must be in [1, {EPOCHS}], got {n_epochs}"
        )
    mean, scale = channel_standardization_stats(X, fold.train_idx)
    set_global_seed(seed)  # reset before every fold: order-independent and paired
    train_loader = DataLoader(
        FoldStandardizedDataset(
            X, y, fold.train_idx, mean, scale,
            label_dtype=task.label_dtype(cfg),
        ),
        batch_size=TRAIN_PROTOCOL["batch_size"], shuffle=True, num_workers=0,
    )
    val_loader = DataLoader(
        FoldStandardizedDataset(
            X, y, fold.val_idx, mean, scale,
            label_dtype=task.label_dtype(cfg),
        ),
        batch_size=TRAIN_PROTOCOL["batch_size"], shuffle=False, num_workers=0,
    )
    model, _ = build_model(cfg, params, X.shape, DEVICE)
    criterion = task.make_criterion(cfg).to(DEVICE)
    optimizer = torch.optim.Adam(
        model.parameters(), lr=params["lr"],
        weight_decay=params.get("weight_decay", 1e-4),
    )
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=EPOCHS
    )
    # Fixed epoch budget: the held-out CV fold is never reused for early
    # stopping. Hyperparameters were already frozen by the canonical inner-val.
    for _ in range(n_epochs):
        model.train()
        for batch_x, batch_y in train_loader:
            optimizer.zero_grad()
            loss = criterion(model(batch_x.to(DEVICE)), batch_y.to(DEVICE))
            loss.backward()
            optimizer.step()
        scheduler.step()

    model.eval()
    predictions, truth = [], []
    with torch.no_grad():
        for batch_x, batch_y in val_loader:
            predictions.append(model(batch_x.to(DEVICE)).cpu().numpy())
            truth.append(batch_y.numpy())
    return per_state_regression_metrics(
        np.vstack(predictions), np.vstack(truth),
        np.asarray(groups)[fold.val_idx],
        n_scour_heads=len(TARGET_SUPPORTS),
    )


def _records_to_error_tensor(
    rows: list[dict],
    arch: str,
    dofs_label: str,
    metric: str,
    *,
    repeats: list[int],
) -> tuple[np.ndarray, np.ndarray]:
    """Align records as state x repeat x seed with hard completeness checks."""

    selected = [r for r in rows
                if r["architecture"] == arch and r["dofs"] == dofs_label]
    try:
        return assemble_state_repeat_seed_tensor(
            selected, seeds=SEEDS, repeats=repeats, value_key=metric
        )
    except ValueError as exc:
        raise RuntimeError(
            f"{arch} on {dofs_label}: invalid {metric} inference tensor: {exc}"
        ) from exc


def _run_finalist_repeated_cv(
    comparators: set,
    winner_key: tuple[str, tuple[int, ...]],
) -> list[dict]:
    """Run/resume finalist-only repeated CV without opening the outer test."""

    print(
        f"  Finalist repeated CV: {len(comparators)} config(s) x "
        f"{len(SEEDS)} seeds x {FINALIST_CV_N_REPEATS} repeats x "
        f"{FINALIST_CV_N_SPLITS} folds; frozen params, no HPO, OUTER TEST closed."
    )
    checkpoint_dir = os.path.join(SUMMARY_DIR, "finalist_cv_checkpoints")
    os.makedirs(checkpoint_dir, exist_ok=True)
    table = read_state_table(os.path.join("data", DATASET))
    canonical_strata = _stratum_keys(
        table, _read_dano_max(os.path.join("data", DATASET))
    )
    strata = finalist_cv_strata(canonical_strata)
    rows: list[dict] = []
    fold_manifest = None
    refit_epochs_by_config: dict[tuple[str, tuple[int, ...], int], int] = {}

    for arch, dofs in sorted(comparators):
        dofs = tuple(int(d) for d in dofs)
        dof_label = _dofs_label(dofs)
        for seed in SEEDS:
            ph, cfg = _find_comparator_config(arch, dofs, seed)
            study = optuna.load_study(study_name=cfg["name"], storage=ph["db"])
            if not _study_is_finished(study, N_TRIALS):
                raise RuntimeError(
                    f"finalist CV found unfinished study {cfg['name']}"
                )
            X, y, _scaler, groups = get_or_create_cache(
                cfg, DATASET, ph["cache_dir"]
            )
            if groups is None:
                raise RuntimeError("finalist repeated CV requires state groups")
            tr_idx, iv_idx = canonical_train_val_split(
                len(y), groups, dataset_name=DATASET
            )
            development_idx = np.sort(np.concatenate([tr_idx, iv_idx]))
            outer_idx = canonical_test_split(
                len(y), groups, dataset_name=DATASET
            )
            if np.intersect1d(development_idx, outer_idx).size:
                raise RuntimeError(
                    "finalist CV development pool intersects the outer test"
                )
            folds = repeated_stratified_group_folds(
                groups, development_idx, strata,
                n_splits=FINALIST_CV_N_SPLITS,
                n_repeats=FINALIST_CV_N_REPEATS,
                seed=FINALIST_CV_SPLIT_SEED,
            )
            this_fold_manifest = {
                "protocol_hash": PROTOCOL_HASH,
                "dataset": DATASET,
                "development_states": sorted(
                    np.unique(np.asarray(groups)[development_idx]).astype(int).tolist()
                ),
                "outer_test_states": sorted(
                    np.unique(np.asarray(groups)[outer_idx]).astype(int).tolist()
                ),
                "stratification": {
                    "policy": "family/anchor + joint crack; joint severity coarsened",
                    "canonical_strata": canonical_strata,
                    "cv_strata": strata,
                },
                "folds": [
                    {"repeat": int(fold.repeat), "fold": int(fold.fold),
                     "validation_states": fold.val_states.astype(int).tolist()}
                    for fold in folds
                ],
            }
            if fold_manifest is None:
                fold_manifest = this_fold_manifest
                _write_json_atomic(
                    os.path.join(SUMMARY_DIR, "finalist_cv_folds.json"),
                    fold_manifest,
                )
            elif fold_manifest != this_fold_manifest:
                raise RuntimeError(
                    "finalist configs produced different repeated-CV folds"
                )
            study_identity = protocol_hash({
                "study_name": study.study_name,
                "best_trial_number": int(study.best_trial.number),
                "best_value": float(study.best_value),
                "best_params": dict(study.best_params),
                "intermediate_values": [
                    [int(epoch), float(value)]
                    for epoch, value in sorted(
                        study.best_trial.intermediate_values.items()
                    )
                ],
            })
            refit_epochs = frozen_checkpoint_epoch_count(
                study.best_trial.intermediate_values, max_epochs=EPOCHS
            )
            recorded_best = min(
                float(value)
                for value in study.best_trial.intermediate_values.values()
            )
            if not math.isclose(
                recorded_best, float(study.best_value),
                rel_tol=1e-12, abs_tol=1e-12,
            ):
                raise RuntimeError(
                    f"best-trial objective/history mismatch for {study.study_name}: "
                    f"study.best_value={study.best_value}, "
                    f"min(intermediate_values)={recorded_best}"
                )
            refit_epochs_by_config[(arch, dofs, int(seed))] = refit_epochs
            combo_digest = short_hash(protocol_hash({
                "architecture": arch, "dofs": list(dofs), "seed": int(seed),
                "protocol_hash": PROTOCOL_HASH,
                "study_identity": study_identity,
                "refit_epochs": refit_epochs,
            }))
            for fold in folds:
                ckpt = os.path.join(
                    checkpoint_dir,
                    f"{combo_digest}_r{fold.repeat}_f{fold.fold}.npz",
                )
                state_m = None
                if os.path.exists(ckpt):
                    try:
                        with np.load(ckpt, allow_pickle=False) as z:
                            if (str(z["protocol_hash"].item()) != PROTOCOL_HASH
                                    or str(z["study_identity"].item())
                                    != study_identity
                                    or str(z["architecture"].item()) != arch
                                    or tuple(z["dofs"].astype(int).tolist()) != dofs
                                    or int(z["seed"].item()) != int(seed)
                                    or int(z["repeat"].item()) != fold.repeat
                                     or int(z["fold"].item()) != fold.fold
                                    or int(z["refit_epochs"].item())
                                    != refit_epochs
                                    or not np.array_equal(
                                        z["state"].astype(int), fold.val_states
                                    )):
                                raise ValueError("checkpoint identity mismatch")
                            state_m = {
                                "state": z["state"],
                                "scour_mse": z["scour_mse"],
                                "all_head_mse": z["all_head_mse"],
                                "predicted_max_scour_pct":
                                    z["predicted_max_scour_pct"],
                            }
                        print(
                            f"    [finalist-cv cached] {arch} {dof_label} "
                            f"seed={seed} repeat={fold.repeat} fold={fold.fold}"
                        )
                    except Exception as exc:
                        raise RuntimeError(
                            f"unreadable/mismatched finalist-CV checkpoint "
                            f"{ckpt}: {exc}; remove that checkpoint and rerun"
                        ) from exc
                if state_m is None:
                    print(
                        f"    [finalist-cv train] {arch} {dof_label} "
                        f"seed={seed} repeat={fold.repeat} fold={fold.fold}"
                    )
                    state_m = _fit_predict_finalist_fold(
                        cfg, study.best_params, X, y, groups, fold, int(seed),
                        refit_epochs,
                    )
                    # The fold constructor and predictions must agree exactly on
                    # the independent validation units before publishing.
                    if not np.array_equal(
                        state_m["state"].astype(int), fold.val_states
                    ):
                        raise RuntimeError(
                            "finalist CV state metrics disagree with fold states"
                        )
                    _atomic_savez(
                        ckpt,
                        protocol_hash=np.asarray(PROTOCOL_HASH),
                        study_identity=np.asarray(study_identity),
                        architecture=np.asarray(arch),
                        dofs=np.asarray(dofs, dtype=np.int64),
                        seed=np.asarray(seed, dtype=np.int64),
                        repeat=np.asarray(fold.repeat, dtype=np.int64),
                        fold=np.asarray(fold.fold, dtype=np.int64),
                        refit_epochs=np.asarray(refit_epochs, dtype=np.int64),
                        state=state_m["state"].astype(np.int64),
                        scour_mse=state_m["scour_mse"],
                        all_head_mse=state_m["all_head_mse"],
                        predicted_max_scour_pct=
                            state_m["predicted_max_scour_pct"],
                    )
                for i, state in enumerate(state_m["state"].astype(int)):
                    rows.append({
                        "architecture": arch, "dofs": dof_label,
                        "n_sensors": len(dofs), "seed": int(seed),
                        "repeat": int(fold.repeat), "fold": int(fold.fold),
                        "refit_epochs": int(refit_epochs),
                        "state": int(state), "family": table["family"][state],
                        "scour_mse": float(state_m["scour_mse"][i]),
                        "all_head_mse": float(state_m["all_head_mse"][i]),
                        "predicted_max_scour_pct":
                            float(state_m["predicted_max_scour_pct"][i]),
                    })

    _write_rows_csv(
        os.path.join(SUMMARY_DIR, "finalist_repeated_cv_state_metrics.csv"),
        rows,
    )
    summary_rows = []
    cv_tensors = {}
    cv_states = {}
    repeats = list(range(FINALIST_CV_N_REPEATS))
    for arch, dofs in sorted(comparators):
        dof_label = _dofs_label(dofs)
        states, scour = _records_to_error_tensor(
            rows, arch, dof_label, "scour_mse", repeats=repeats
        )
        states2, all_head = _records_to_error_tensor(
            rows, arch, dof_label, "all_head_mse", repeats=repeats
        )
        if not np.array_equal(states, states2):
            raise RuntimeError("metric tensors disagree on finalist-CV states")
        cv_tensors[(arch, tuple(dofs))] = scour
        cv_states[(arch, tuple(dofs))] = states
        scour_ci = hierarchical_state_seed_bootstrap(
            scour, n_boot=BOOTSTRAP_N, seed=BOOTSTRAP_SEED, ci=0.95
        )
        all_ci = hierarchical_state_seed_bootstrap(
            all_head, n_boot=BOOTSTRAP_N, seed=BOOTSTRAP_SEED, ci=0.95
        )
        scour_by_seed = scour.mean(axis=0).mean(axis=0)
        all_by_seed = all_head.mean(axis=0).mean(axis=0)
        summary_rows.append({
            "architecture": arch, "dofs": dof_label, "n_sensors": len(dofs),
            "n_states": len(states), "n_repeats": FINALIST_CV_N_REPEATS,
            "n_seeds": len(SEEDS),
            "scour_mse": scour_ci["estimate"],
            "scour_mse_ci95_lo": scour_ci["ci_lo"],
            "scour_mse_ci95_hi": scour_ci["ci_hi"],
            "scour_mse_seed_iqr": float(
                np.subtract(*np.percentile(scour_by_seed, [75, 25]))
            ),
            "all_head_mse": all_ci["estimate"],
            "all_head_mse_ci95_lo": all_ci["ci_lo"],
            "all_head_mse_ci95_hi": all_ci["ci_hi"],
            "all_head_mse_seed_iqr": float(
                np.subtract(*np.percentile(all_by_seed, [75, 25]))
            ),
        })
    ranked_cv = sorted(summary_rows, key=lambda row: row["scour_mse"])
    for rank, row in enumerate(ranked_cv, start=1):
        row["diagnostic_scour_rank"] = rank
        row["is_frozen_canonical_winner"] = (
            row["architecture"] == winner_key[0]
            and row["dofs"] == _dofs_label(winner_key[1])
        )
    winner_cv_row = next(
        row for row in ranked_cv if row["is_frozen_canonical_winner"]
    )
    winner_cv_rank = int(winner_cv_row["diagnostic_scour_rank"])
    if winner_cv_rank != 1:
        print(
            f"  [finalist CV] STABILITY WARNING: the frozen canonical inner-val "
            f"winner ranks {winner_cv_rank}/{len(ranked_cv)} in the diagnostic "
            "repeated CV. Selection remains frozen by protocol; report this "
            "instability and do not claim a universally best architecture/pair."
        )
    _write_rows_csv(
        os.path.join(SUMMARY_DIR, "finalist_repeated_cv_summary.csv"),
        ranked_cv,
    )

    # Paired finalist contrasts over the exact state x repeat x seed cells.
    # These are development-only robustness diagnostics and cannot alter the
    # already-frozen winner.
    cv_contrast_rows = []
    cv_contrast_summary = []
    cv_family_by_state = {
        int(r["state"]): str(r["family"]) for r in rows
    }
    winner_states = cv_states[winner_key]
    winner_tensor = cv_tensors[winner_key]
    for comparator_key in sorted(comparators):
        if comparator_key == winner_key:
            continue
        if not np.array_equal(winner_states, cv_states[comparator_key]):
            raise RuntimeError(
                f"finalist-CV paired states differ: {winner_key} vs "
                f"{comparator_key}"
            )
        comparator_tensor = cv_tensors[comparator_key]
        contrast = paired_state_contrast(
            winner_tensor, comparator_tensor,
            n_boot=BOOTSTRAP_N, seed=BOOTSTRAP_SEED, ci=0.95,
        )
        comp_arch, comp_dofs = comparator_key
        for si, state in enumerate(winner_states):
            for repeat in range(FINALIST_CV_N_REPEATS):
                for seed_i, seed in enumerate(SEEDS):
                    win_err = float(winner_tensor[si, repeat, seed_i])
                    cmp_err = float(comparator_tensor[si, repeat, seed_i])
                    cv_contrast_rows.append({
                        "winner_architecture": winner_key[0],
                        "winner_dofs": _dofs_label(winner_key[1]),
                        "comparator_architecture": comp_arch,
                        "comparator_dofs": _dofs_label(comp_dofs),
                        "state": int(state),
                        "family": cv_family_by_state[int(state)],
                        "repeat": int(repeat),
                        "seed": int(seed), "winner_scour_mse": win_err,
                        "comparator_scour_mse": cmp_err,
                        "difference_winner_minus_comparator": win_err - cmp_err,
                    })
        cv_contrast_summary.append({
            "winner_architecture": winner_key[0],
            "winner_dofs": _dofs_label(winner_key[1]),
            "comparator_architecture": comp_arch,
            "comparator_dofs": _dofs_label(comp_dofs),
            "effect": "difference of cross-seed medians: winner minus comparator "
                      "scour MSE (negative favours winner)",
            "estimate": contrast["estimate"],
            "ci95_lo": contrast["ci_lo"],
            "ci95_hi": contrast["ci_hi"],
            "descriptive_bootstrap_fraction_winner_better":
                contrast["descriptive_bootstrap_fraction_winner_better"],
            "n_states": contrast["n_states"],
            "n_repeats": contrast["n_repeats"],
            "n_seeds": contrast["n_seeds"],
        })
    _write_rows_csv(
        os.path.join(SUMMARY_DIR, "paired_finalist_cv_state_contrasts.csv"),
        cv_contrast_rows,
    )
    _write_rows_csv(
        os.path.join(SUMMARY_DIR, "paired_finalist_cv_contrast_summary.csv"),
        cv_contrast_summary,
    )

    # Planning diagnostic for the next regeneration.  Average the selected
    # winner's repeated-CV probe over repeat/seed first, leaving one independent
    # value per state; do not inflate n with passages or repeated predictions.
    winner_arch, winner_dofs = winner_key
    winner_label = _dofs_label(winner_dofs)
    winner_rows = [r for r in rows
                   if r["architecture"] == winner_arch
                   and r["dofs"] == winner_label]
    planning_families = {"nuisance_only", "target_healthy", "bearing_only"}
    planning_states = {
        int(r["state"]) for r in winner_rows
        if str(table["family"][int(r["state"])]) in planning_families
    }
    values_by_state = {}
    for state in sorted(planning_states):
        vals = [float(r["predicted_max_scour_pct"]) for r in winner_rows
                if int(r["state"]) == state]
        values_by_state[state] = float(np.mean(vals))
    # Use the same analysis strata as the split (including anchor target and
    # joint severity/crack bins), otherwise pooling all scour_only targets could
    # hide that each individual target still has only one or two test states.
    family_by_state = {state: str(strata[state]) for state in values_by_state}
    current_total_by_family = {
        key: int(sum(stratum == key for stratum in strata))
        for key in sorted(set(strata))
    }
    family_rows = mcse_family_size_recommendations(
        values_by_state, family_by_state,
        target_mcse=FAMILY_TARGET_MCSE_PCT,
        min_evaluation_states=FAMILY_MIN_EVAL_STATES,
        evaluation_fraction=0.20,
        current_total_by_family=current_total_by_family,
    )
    _write_rows_csv(
        os.path.join(SUMMARY_DIR, "family_size_mcse_recommendations.csv"),
        family_rows,
    )
    _write_json_atomic(
        os.path.join(SUMMARY_DIR, "finalist_repeated_cv_manifest.json"),
        {
            "protocol_hash": PROTOCOL_HASH,
            "policy": STATISTICAL_INFERENCE_PROTOCOL["finalist_repeated_cv"],
            "comparators": [
                {"architecture": arch, "dofs": list(dofs)}
                for arch, dofs in sorted(comparators)
            ],
            "winner": {
                "architecture": winner_arch, "dofs": list(winner_dofs),
                "diagnostic_cv_rank": winner_cv_rank,
                "diagnostic_cv_rank_denominator": len(ranked_cv),
                "diagnostic_cv_stable_rank1": winner_cv_rank == 1,
                "selection_note": "CV is diagnostic and cannot re-rank the "
                                  "canonical inner-validation selection",
            },
            "outer_test_observations_accessed": False,
            "outer_test_membership_used_only_for_disjointness_assertion": True,
            "state_tensor_layout": "state x repeat x seed",
            "n_fixed_refits": (
                len(comparators) * len(SEEDS)
                * FINALIST_CV_N_REPEATS * FINALIST_CV_N_SPLITS
            ),
            "planned_refit_epochs": int(sum(
                epochs * FINALIST_CV_N_REPEATS * FINALIST_CV_N_SPLITS
                for epochs in refit_epochs_by_config.values()
            )),
            "max_planned_refit_epochs": (
                len(comparators) * len(SEEDS)
                * FINALIST_CV_N_REPEATS * FINALIST_CV_N_SPLITS * EPOCHS
            ),
            "refit_epochs_by_config": [
                {
                    "architecture": arch,
                    "dofs": list(dofs),
                    "seed": seed,
                    "refit_epochs": epochs,
                }
                for (arch, dofs, seed), epochs
                in sorted(refit_epochs_by_config.items())
            ],
        },
    )
    print(
        f"  Finalist repeated CV complete: {len(rows)} independent-state "
        f"prediction rows -> {SUMMARY_DIR}"
    )
    return rows


def _outer_test_hierarchical_inference(
    state_rows: list[dict],
    comparators: set,
    winner_key: tuple[str, tuple[int, ...]],
    aggregate_rows: list[dict],
) -> list[dict]:
    """Cross-seed CIs and paired state contrasts on the frozen report set."""

    repeats = [0]  # outer test has one prediction set per algorithmic seed
    tensors = {}
    state_vectors = {}
    for arch, dofs in sorted(comparators):
        dof_label = _dofs_label(dofs)
        states, scour = _records_to_error_tensor(
            state_rows, arch, dof_label, "scour_mse", repeats=repeats
        )
        states2, all_head = _records_to_error_tensor(
            state_rows, arch, dof_label, "all_head_mse", repeats=repeats
        )
        if not np.array_equal(states, states2):
            raise RuntimeError("outer-test metric tensors disagree on states")
        tensors[(arch, tuple(dofs))] = {
            "scour_mse": scour, "all_head_mse": all_head
        }
        state_vectors[(arch, tuple(dofs))] = states
        scour_ci = hierarchical_state_seed_bootstrap(
            scour, n_boot=BOOTSTRAP_N, seed=BOOTSTRAP_SEED, ci=0.95
        )
        all_ci = hierarchical_state_seed_bootstrap(
            all_head, n_boot=BOOTSTRAP_N, seed=BOOTSTRAP_SEED, ci=0.95
        )
        row = next(
            (r for r in aggregate_rows
             if r["architecture"] == arch and r["dofs"] == dof_label),
            None,
        )
        if row is None:
            raise RuntimeError(
                f"no aggregate outer-test row for {arch} on {dof_label}"
            )
        row["scour_mse"] = round(float(scour_ci["estimate"]), 4)
        row["agg_mse"] = round(float(all_ci["estimate"]), 4)
        row["scour_mse_ci95_lo"] = round(float(scour_ci["ci_lo"]), 4)
        row["scour_mse_ci95_hi"] = round(float(scour_ci["ci_hi"]), 4)
        row["agg_mse_ci95_lo"] = round(float(all_ci["ci_lo"]), 4)
        row["agg_mse_ci95_hi"] = round(float(all_ci["ci_hi"]), 4)
        row["ci_independent_states"] = int(scour_ci["n_states"])
        row["ci_method"] = "state-first hierarchical; cross-seed median inside"
        scour_by_seed = scour.mean(axis=0).mean(axis=0)
        all_by_seed = all_head.mean(axis=0).mean(axis=0)
        row["scour_mse_seed_iqr"] = round(float(
            np.subtract(*np.percentile(scour_by_seed, [75, 25]))
        ), 4)
        row["all_head_mse_seed_iqr"] = round(float(
            np.subtract(*np.percentile(all_by_seed, [75, 25]))
        ), 4)

    winner_states = state_vectors[winner_key]
    winner_errors = tensors[winner_key]["scour_mse"]
    contrast_state_rows = []
    contrast_summary = []
    outer_family_by_state = {
        int(r["state"]): str(r["family"]) for r in state_rows
    }
    for comparator_key in sorted(comparators):
        if comparator_key == winner_key:
            continue
        comp_states = state_vectors[comparator_key]
        if not np.array_equal(winner_states, comp_states):
            raise RuntimeError(
                f"paired contrast state mismatch: {winner_key} vs {comparator_key}"
            )
        comp_errors = tensors[comparator_key]["scour_mse"]
        contrast = paired_state_contrast(
            winner_errors, comp_errors,
            n_boot=BOOTSTRAP_N, seed=BOOTSTRAP_SEED, ci=0.95,
        )
        comp_arch, comp_dofs = comparator_key
        for si, state in enumerate(winner_states):
            for seed_i, seed in enumerate(SEEDS):
                win_err = float(winner_errors[si, 0, seed_i])
                cmp_err = float(comp_errors[si, 0, seed_i])
                contrast_state_rows.append({
                    "winner_architecture": winner_key[0],
                    "winner_dofs": _dofs_label(winner_key[1]),
                    "comparator_architecture": comp_arch,
                    "comparator_dofs": _dofs_label(comp_dofs),
                    "state": int(state),
                    "family": outer_family_by_state[int(state)],
                    "seed": int(seed),
                    "winner_scour_mse": win_err,
                    "comparator_scour_mse": cmp_err,
                    "difference_winner_minus_comparator": win_err - cmp_err,
                })
        contrast_summary.append({
            "winner_architecture": winner_key[0],
            "winner_dofs": _dofs_label(winner_key[1]),
            "comparator_architecture": comp_arch,
            "comparator_dofs": _dofs_label(comp_dofs),
            "effect": "difference of cross-seed medians: winner minus comparator "
                      "scour MSE (negative favours winner)",
            "estimate": contrast["estimate"],
            "ci95_lo": contrast["ci_lo"],
            "ci95_hi": contrast["ci_hi"],
            "descriptive_bootstrap_fraction_winner_better":
                contrast["descriptive_bootstrap_fraction_winner_better"],
            "n_states": contrast["n_states"], "n_seeds": contrast["n_seeds"],
        })
    _write_rows_csv(
        os.path.join(SUMMARY_DIR, "paired_outer_test_state_contrasts.csv"),
        contrast_state_rows,
    )
    _write_rows_csv(
        os.path.join(SUMMARY_DIR, "paired_outer_test_contrast_summary.csv"),
        contrast_summary,
    )
    return aggregate_rows


def _median_leaderboard(rows: list[dict], csv_name: str = "leaderboard_median.csv") -> list[dict]:
    """Seed-aggregated leaderboard: median + IQR per (phase, architecture, dofs).

    The paper-facing table (see ablation methodology: report median, not mean -
    occasional HPO/init collapses inflate the mean). One row per config; the
    per-seed rows stay available in leaderboard.csv.
    """
    groups: dict[tuple, list[dict]] = {}
    for r in rows:
        groups.setdefault((r["phase"], r["architecture"], r["dofs"]), []).append(r)

    num_cols = [
        k for k in rows[0]
        if k not in (
            "phase", "architecture", "dofs", "seed", "n_sensors", "seed_ids"
        )
    ]
    agg_rows: list[dict] = []
    for (phase, arch, dofs), grp in groups.items():
        row = {
            "phase": phase, "architecture": arch, "dofs": dofs,
            "n_sensors": grp[0]["n_sensors"], "n_seeds": len(grp),
            "seed_ids": sorted(int(g["seed"]) for g in grp),
        }
        for col in num_cols:
            vals = [g[col] for g in grp
                    if isinstance(g.get(col), (int, float))]
            if not vals:
                continue
            # Keep the SELECTION metric (inner-val) at full precision; round only
            # display metrics (audit R7.1 P3 — avoid flipping near-tied pairs).
            row[col] = float(np.median(vals)) if col == "inner_val_mse" \
                else round(float(np.median(vals)), 4)
            if col in ("agg_mse", "inner_val_mse") and len(vals) > 1:
                q75, q25 = np.percentile(vals, [75, 25])
                row[f"{col}_iqr"] = round(float(q75 - q25), 4)
        agg_rows.append(row)

    # Rank by the SELECTION metric (inner-val), not the test metric (audit R6 C2).
    agg_rows.sort(key=lambda r: r.get("inner_val_mse", float("inf")))
    csv_path = os.path.join(SUMMARY_DIR, csv_name)
    _write_rows_csv(csv_path, agg_rows)
    print(f"  Median leaderboard ({len(agg_rows)} configs x {len(SEEDS)} seeds) "
          f"-> {csv_path}")
    return agg_rows


def _find_cfg(row: dict) -> tuple[dict | None, dict | None]:
    """(phase, config) dicts for a leaderboard row, or (None, None).

    AUDIT R5 2026-07-17: match the row's DOFS and SEED, not just its architecture.
    Per-seed rows (leaderboard / disentanglement) now resolve to their OWN seed's
    model — previously every seed mapped to the SEEDS[0] config, so a 'seed 1337'
    or 'seed 2026' row plotted/reported the seed-42 predictions. A median row
    (no seed) resolves to the SEEDS[0] representative."""
    ph = next((p for p in _RAN_PHASES if p["phase_label"] == row["phase"]), None)
    if ph is None:
        return None, None
    want_seed = row.get("seed", SEEDS[0])
    want_dofs = row.get("dofs")

    def _dofs_str(c):
        return "+".join(IDX_TO_DOF_NAME[d] for d in c["dofs"])

    cfg = next((c for c in ph["configs"]
                if c["name_short"] == row["architecture"]
                and c.get("seed") == want_seed
                and (want_dofs is None or _dofs_str(c) == want_dofs)), None)
    if cfg is None:      # median row (no exact seed) -> SEEDS[0] representative
        cfg = next((c for c in ph["configs"]
                    if c["name_short"] == row["architecture"]
                    and c.get("seed") == SEEDS[0]
                    and (want_dofs is None or _dofs_str(c) == want_dofs)), None)
    return ph, cfg


def _predictions(ph: dict, cfg: dict) -> tuple[np.ndarray, np.ndarray, np.ndarray] | None:
    """Champion predictions, ground truth and per-sample STATE ids on the outer
    TEST set: (P, T, states). `states` indexes the dataset's state-family table
    (Feature A) so probes select samples by generated IDENTITY."""
    weights = os.path.join(ph["output_dir"], cfg["name"], "DT_champion_weights.pth")
    if not os.path.exists(weights):
        return None
    study = optuna.load_study(study_name=cfg["name"], storage=ph["db"])
    verify_digital_twin_package(study, cfg, os.path.dirname(weights))
    loader, shape, test_states = _test_loader(cfg, ph["cache_dir"])
    model, _ = build_model(cfg, study.best_params, shape, DEVICE)
    model.load_state_dict(torch.load(weights, map_location=DEVICE))
    model.eval()
    preds, trues = [], []
    with torch.no_grad():
        for bx, by in loader:
            preds.append(model(bx.to(DEVICE)).cpu().numpy())
            trues.append(by.numpy())
    return np.vstack(preds), np.vstack(trues), test_states


def disentanglement_report(rows: list[dict]) -> None:
    """Leakage / false-positive probes by state-family IDENTITY (Feature A,
    2026-07-19 — replaces the old threshold-on-labels version, which could not
    distinguish `target_healthy` from `nuisance_only` because per-STATE
    persistent nuisances are invisible in `y`).

    On the outer TEST set, per config with bearing heads:
      * bearing_only  states -> mean of max predicted SCOUR   (false scour —
                                the dangerous case: a seized bearing must not
                                look like scour);
      * scour_only    states -> mean of max predicted BEARING (false bearing);
      * nuisance_only states -> mean of max predicted scour AND bearing (the
                                invariance probe: crack forced ON, all heads 0);
      * target_healthy states -> the same false-positive baselines on clean
                                zero-head states (crack forced OFF).
    Coverage of every family in TEST is GUARANTEED by the stratified split, so
    an empty probe here is a split/loader BUG and raises (the old probabilistic
    WARNING is gone). Families absent from the DATASET (e.g. nuisance_only at
    no-crack rungs) report NaN and are noted, not errors."""
    n_s = len(TARGET_SUPPORTS)
    from core.dataset import read_state_table
    table = read_state_table(os.path.join("data", DATASET))
    fam_by_state = np.array(table["family"])
    present_fams = set(table["family"])

    def _state_probe(block: np.ndarray, states: np.ndarray,
                     mask: np.ndarray) -> list[dict]:
        """One false-response row per independent generated state."""
        state_rows = []
        for state in sorted(np.unique(states[mask]).astype(int).tolist()):
            selected = block[(states == state) & mask]
            positive = np.maximum(selected, 0.0)
            state_rows.append({
                "state": state,
                # Primary false-positive amplitude: a negative prediction cannot
                # be interpreted as "better than zero".
                "positive_part_pct":
                    float(positive.max(axis=1).mean()),
                # Diagnostics preserve signed direction and total zero-target
                # error instead of hiding clipping behaviour.
                "signed_max_bias_pct":
                    float(selected.max(axis=1).mean()),
                "zero_target_rmse_pct":
                    float(np.sqrt(np.square(selected).mean())),
            })
        return state_rows

    out: list[dict] = []
    state_probe_rows: list[dict] = []
    print("\n  --- state-first disentanglement / false-positive probes ---")
    for r in rows:
        ph, cfg = _find_cfg(r)
        if cfg is None or not cfg.get("bearing_targets"):
            continue
        pt = _predictions(ph, cfg)
        if pt is None:
            continue
        P, _T, states = pt
        fams = fam_by_state[states]            # family per TEST sample
        Ps, Pb = P[:, :n_s], P[:, n_s:]        # pred scour / bearing heads
        m_bear = fams == "bearing_only"
        m_scour = fams == "scour_only"
        m_nuis = fams == "nuisance_only"
        m_healthy = fams == "target_healthy"
        # A family that EXISTS in this dataset but has no TEST samples means
        # the stratified-split guarantee was violated — that is a bug, never
        # a statistic to report around.
        for fam, mask in (("bearing_only", m_bear), ("scour_only", m_scour),
                          ("nuisance_only", m_nuis), ("target_healthy", m_healthy)):
            if fam in present_fams and not mask.any():
                raise RuntimeError(
                    f"disentanglement: family {fam!r} exists in {DATASET} but "
                    f"has ZERO outer-test samples — stratified-split guarantee "
                    f"violated (split/loader bug; do not report).")
        specs = {
            "false_scour_on_bearing_only": (Ps, "bearing_only", m_bear),
            "false_bearing_on_scour_only": (Pb, "scour_only", m_scour),
            "false_scour_on_nuisance_only": (Ps, "nuisance_only", m_nuis),
            "false_bearing_on_nuisance_only": (Pb, "nuisance_only", m_nuis),
            "false_scour_on_healthy": (Ps, "target_healthy", m_healthy),
            "false_bearing_on_healthy": (Pb, "target_healthy", m_healthy),
        }
        seed = int(cfg.get("seed", SEEDS[0]))
        row = {
            "architecture": cfg["name_short"], "dofs": r["dofs"],
            "seed": seed,
        }
        family_masks = {
            "bearing_only": m_bear, "scour_only": m_scour,
            "nuisance_only": m_nuis, "target_healthy": m_healthy,
        }
        for family, mask in family_masks.items():
            short = "healthy" if family == "target_healthy" else family
            row[f"n_{short}_states"] = int(len(np.unique(states[mask])))
            row[f"n_{short}_passages"] = int(mask.sum())
        for probe, (block, family, mask) in specs.items():
            state_rows = _state_probe(block, states, mask)
            for metric in (
                "positive_part_pct", "signed_max_bias_pct",
                "zero_target_rmse_pct",
            ):
                values = [state_row[metric] for state_row in state_rows]
                row[f"{probe}_{metric}"] = (
                    round(float(np.mean(values)), 3)
                    if values else float("nan")
                )
            for state_row in state_rows:
                state_probe_rows.append({
                    "architecture": cfg["name_short"], "dofs": r["dofs"],
                    "seed": seed, "state": state_row["state"],
                    "family": family, "probe": probe, **state_row,
                })
        out.append(row)
        print(
            f"    {cfg['name_short']:16} {r['dofs']:28} seed={seed:<5} "
            f"positive false-scour(bearing)="
            f"{row['false_scour_on_bearing_only_positive_part_pct']:6.2f}%  "
            f"positive false-bearing(scour)="
            f"{row['false_bearing_on_scour_only_positive_part_pct']:6.2f}%  "
            f"positive false-scour(nuis)="
            f"{row['false_scour_on_nuisance_only_positive_part_pct']:6.2f}%"
        )
    if not out:
        return
    if "nuisance_only" not in present_fams:
        print(f"  [disentanglement] NOTE: {DATASET} has no nuisance_only states "
              f"(no crack EOV at this rung) — those columns are NaN by design.")
    print(
        "  [disentanglement] independent outer-test states / passages: "
        f"bearing_only={out[0]['n_bearing_only_states']}/"
        f"{out[0]['n_bearing_only_passages']}, "
        f"scour_only={out[0]['n_scour_only_states']}/"
        f"{out[0]['n_scour_only_passages']}, "
        f"nuisance_only={out[0]['n_nuisance_only_states']}/"
        f"{out[0]['n_nuisance_only_passages']}, "
        f"healthy={out[0]['n_healthy_states']}/"
        f"{out[0]['n_healthy_passages']}."
    )
    csv_path = os.path.join(SUMMARY_DIR, "disentanglement.csv")
    _write_rows_csv(csv_path, out)
    _write_rows_csv(
        os.path.join(SUMMARY_DIR, "disentanglement_state_metrics.csv"),
        state_probe_rows,
    )

    # Paper-facing uncertainty for the primary positive-part amplitude. The
    # exact same outer states are aligned across the fixed seed set. With only
    # one nuisance state the point estimate is retained as an explicitly
    # exploratory diagnostic; fabricating a bootstrap interval is forbidden.
    summary_rows: list[dict] = []
    config_keys = sorted({
        (r["architecture"], r["dofs"], r["probe"])
        for r in state_probe_rows
    })
    for architecture, dofs, probe in config_keys:
        selected = [
            r for r in state_probe_rows
            if r["architecture"] == architecture and r["dofs"] == dofs
            and r["probe"] == probe
        ]
        states_here = sorted({int(r["state"]) for r in selected})
        seeds_here = sorted({int(r["seed"]) for r in selected})
        expected_cells = len(states_here) * len(SEEDS)
        if seeds_here != sorted(SEEDS) or len(selected) != expected_cells:
            raise RuntimeError(
                f"disentanglement tensor incomplete for {architecture}, "
                f"{dofs}, {probe}: seeds={seeds_here}, rows={len(selected)}/"
                f"{expected_cells}.")
        state_pos = {state: i for i, state in enumerate(states_here)}
        seed_pos = {seed: i for i, seed in enumerate(SEEDS)}
        tensor = np.full((len(states_here), 1, len(SEEDS)), np.nan)
        for record in selected:
            key = (state_pos[int(record["state"])], 0,
                   seed_pos[int(record["seed"])])
            if np.isfinite(tensor[key]):
                raise RuntimeError(
                    f"duplicate disentanglement cell {architecture}/{dofs}/"
                    f"{probe}/{record['state']}/{record['seed']}.")
            tensor[key] = float(record["positive_part_pct"])
        if not np.isfinite(tensor).all():
            raise RuntimeError("non-finite disentanglement state tensor")
        estimate = float(np.median(tensor.mean(axis=0), axis=1).mean())
        if len(states_here) >= 2:
            inference = hierarchical_state_seed_bootstrap(
                tensor, n_boot=BOOTSTRAP_N, seed=BOOTSTRAP_SEED, ci=0.95
            )
            lo, hi = inference["ci_lo"], inference["ci_hi"]
            status = "state-first bootstrap CI"
        else:
            lo = hi = float("nan")
            status = "exploratory only: one independent outer state; no CI"
        summary_rows.append({
            "architecture": architecture, "dofs": dofs, "probe": probe,
            "estimand": "cross-seed median of state-mean positive-part amplitude",
            "estimate_pct": estimate, "ci95_lo_pct": lo, "ci95_hi_pct": hi,
            "n_states": len(states_here), "n_seeds": len(SEEDS),
            "inference_status": status,
        })
    _write_rows_csv(
        os.path.join(SUMMARY_DIR, "disentanglement_statefirst_summary.csv"),
        summary_rows,
    )
    print(
        f"  Disentanglement -> {csv_path}; primary amplitudes use positive "
        "parts and independent-state counts. Sparse families are labelled "
        "exploratory, never pseudo-replicated."
    )


def _parity_plot_for_best(best_row: dict) -> None:
    """Predicted-vs-true scatter per target head for the leaderboard winner."""
    ph, cfg = _find_cfg(best_row)
    if cfg is None:
        return
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:                                        # noqa: BLE001
        print("  [summary] matplotlib unavailable - parity plot skipped.")
        return
    pt = _predictions(ph, cfg)
    if pt is None:
        return
    P, T, _states = pt

    n_s = len(TARGET_SUPPORTS)
    bt = cfg.get("bearing_targets") or []
    n = P.shape[1]
    fig, axes = plt.subplots(1, n, figsize=(5 * n, 4.5), squeeze=False)
    for i in range(n):
        ax = axes[0, i]
        is_scour = i < n_s
        label = (f"Scour support {TARGET_SUPPORTS[i]}" if is_scour
                 else f"Bearing {bt[i - n_s] if (i - n_s) < len(bt) else i - n_s}")
        unit = "scour (%)" if is_scour else "seized (%)"
        ax.scatter(T[:, i], P[:, i], s=10, alpha=0.4)
        lo, hi = 0, max(60 if is_scour else 100, float(T[:, i].max()) + 5)
        ax.plot([lo, hi], [lo, hi], "k--", lw=1)
        ax.set_xlim(lo, hi); ax.set_ylim(lo, hi)
        ax.set_xlabel(f"True {unit}"); ax.set_ylabel(f"Predicted {unit}")
        ax.set_title(label)
        ax.set_aspect("equal", "box")
    # Label the seed of the model ACTUALLY plotted (cfg, = SEEDS[0]), not the
    # leaderboard row's seed, so the figure caption can't mislabel it (audit R4).
    best_row = {**best_row, "seed": cfg.get("seed", SEEDS[0])}
    fig.suptitle(f"{STAGE} parity - {best_row['architecture']} on {best_row['dofs']}"
                 f" (seed {best_row.get('seed', '?')})")
    fig.tight_layout()
    out = os.path.join(SUMMARY_DIR, "parity_best.png")
    fig.savefig(out, dpi=150); plt.close(fig)
    print(f"  Parity plot -> {out}")


