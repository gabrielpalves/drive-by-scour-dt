def _required_absolute_campaign_path(name: str, value: str) -> str:
    """Return one explicit absolute coordination path or fail closed."""

    if not isinstance(value, str) or not value.strip():
        raise SystemExit(
            f"{name} is required. Point it at a durable absolute path outside "
            "the extracted bundle's disposable results tree."
        )
    path = Path(value).expanduser()
    if not path.is_absolute():
        raise SystemExit(
            f"{name} must be absolute; got {value!r}. Relative paths cannot "
            "authenticate separate bundle workspaces."
        )
    probe = path
    while True:
        if os.path.lexists(probe) and probe.is_symlink():
            raise SystemExit(
                f"{name} must not traverse a symlink: {probe}"
            )
        if probe.parent == probe:
            break
        probe = probe.parent
    resolved = path.resolve(strict=False)
    workspace = Path.cwd().resolve(strict=False)
    if resolved == workspace or workspace in resolved.parents:
        raise SystemExit(
            f"{name} must be durable and outside the disposable campaign "
            f"workspace {workspace}; got {resolved}"
        )
    return str(resolved)


