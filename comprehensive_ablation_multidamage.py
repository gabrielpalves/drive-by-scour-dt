    if _manifest is None:
        _block, anchor = execution_block_for_stage(
            STAGE, EXECUTION_BLOCK_POLICY)
        raise SystemExit(
            f"{STAGE}: no authenticated block-local reference. Run "
            f"STAGE={anchor!r} first on this exact physical execution block.")
