"""
comprehensive_ablation_multidamage.py
======================================
Stage-0 multi-damage ablation: can a single drive-by pass LOCALISE and QUANTIFY
scour at TWO independent piers? Drives the same Optuna/training pipeline as the
single-scour ablation, but in MULTI-OUTPUT REGRESSION mode (one continuous head
per target support), against a dataset generated by scour_MATLAB/A00_Run.m with
the matching ladder preset (for example ``STAGE='s0_scour'``).

TURNKEY: run once, no manual editing. The script
    1. At s0, runs a diagnostic single-DOF sweep (8 sensors) under all arms.
    2. At s0 and deployment-selection rungs, runs the COMPLETE four-
       architecture x C(8,2)=28 pair factorial; other search rungs sweep all
       pairs under the carried architecture and frozen rungs keep the s0 pair.
    3. Selects the architecture-pair combination jointly on median inner-
       validation scour MSE; the full 8-DOF array is a non-selectable control.
    4. Writes a results summary (leaderboard CSV with one row per seed +
       a seed-aggregated median/IQR leaderboard + per-head MSE + localisation
       accuracy + a predicted-vs-true parity plot).

ARCHITECTURE POLICY: s0 selects the ladder architecture+pair jointly. Frozen
one-factor rungs carry that combination. The fully realistic s16/s23 rungs
re-open the complete architecture×placement question for a separate,
exploratory deployment recommendation that never overwrites the ladder lineage.

Each configuration uses the pre-registered independent Optuna seeds (default
three), reported as median + IQR. Candidate HPO and selection use one canonical
state-grouped development split; an immutable grouped outer test is opened only
after selection freezes. Search rungs additionally run 5-fold x 2-repeat
state-grouped CV on the winner and pre-registered finalists, with fold-local
scaling and frozen hyperparameters, as a split-stability diagnostic. It does not
replace the outer-test estimate. The full 8-DOF array also runs as a
non-selectable sensor-budget control, so the 2-vs-8 economy claim is measured at
every rung.

Architectures (cost-aware):
    1. PAA + multi-rate pooling (N-HiTS-inspired).
    2. PAA + Space2Vec + multi-rate pooling.
       (Space2Vec grounds the signal to bridge position - plausibly useful when
        the task is *which* pier.)
    3. PAA + LSTM + multi-rate pooling.
    4. PAA + CNN global-average pooling — no-multi-rate ablation control.

The task switch is `task='regression'` in each config (core/task.py). Leave it
out - or run the single-scour scripts - to get the original classification.
"""

