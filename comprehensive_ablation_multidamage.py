    _write_rows_csv(
        os.path.join(SUMMARY_DIR, "paired_finalist_cv_contrast_summary.csv"),
        cv_contrast_summary,
    )

    # Planning diagnostic for the next regeneration.  Average the selected
    # winner's repeated-CV probe over repeat/seed first, leaving one independent
    # value per state; do not inflate n with passages or repeated predictions.
    winner_arch, winner_dofs = winner_key
