def _study_block_reference_sha256() -> str | None:
    """Return the causal block-reference pin carried by one study.

    Anchor studies necessarily use ``None``: their reference does not exist
    until after the complete inner-validation selection has frozen, and the
    reference itself already hashes that frozen-selection artifact.  Every
    follower must instead carry the exact externally supplied digest.
    """

    _block, anchor = execution_block_for_stage(
        STAGE, EXECUTION_BLOCK_POLICY
    )
    if STAGE == anchor:
        return None
    if (
        not isinstance(BLOCK_REFERENCE_SHA256, str)
        or len(BLOCK_REFERENCE_SHA256) != 64
        or any(
            char not in "0123456789abcdef"
            for char in BLOCK_REFERENCE_SHA256
        )
    ):
        raise RuntimeError(
            f"{STAGE}: follower study lacks its exact lowercase "
            "block-reference SHA-256"
        )
    return BLOCK_REFERENCE_SHA256


def make_config(arch: dict, dofs: list[int], seed: int) -> dict:
    """One experiment_path entry - a multi-output REGRESSION config."""
    if _EXECUTION_ATTESTATION is None:
        raise RuntimeError(
            "execution block has not been attested. The campaign driver must "
            "validate/create its block receipt before constructing studies."
        )
    if (
        STAGE not in ARCH_SELECTION_STAGES
        and _CHAMPION_EXECUTION_STATUS is None
    ):
        raise RuntimeError(
            "block-local reference has not been validated against the current "
            "execution block; refusing to construct downstream studies."
        )
    dof_str = "_".join(str(d) for d in dofs)
    config = {
        "name":            f"{arch['name_short']}_DOFs_{dof_str}_seed{seed}{_cfg_suffix()}",
        "seed":            seed,
        "sensor_noise":    SENSOR_NOISE,
        "name_short":      arch["name_short"],
        "method":          arch["method"],
        "dofs":            list(dofs),
        "discretization":  DISCRETIZATION,
        "use_space2vec":   arch["use_space2vec"],
        "use_lstm":        arch["use_lstm"],
        "use_nhits":       arch["use_nhits"],
        "model_type":      arch["model_type"],
        # --- the multi-output regression switch (core/task.py) ---
        "task":            TASK,
        "target_supports": TARGET_SUPPORTS,
        "bearing_targets": BEARING_TARGETS,   # None for Stage 0
        # Unified protocol hash (2026-07-19): travels with the config so the
        # pipeline stamps it into DT_metadata.json next to the weights.
        "protocol_hash":   PROTOCOL_HASH,
        "protocol_core_hash": PROTOCOL_CORE_HASH,
        "protocol_descriptor": PROTOCOL_FULL_DESC,
        # Actual hardware identity is intentionally outside PROTOCOL_*_HASH,
        # but is an exact resume/export gate in training.pipeline.
        "execution_runtime": _EXECUTION_ATTESTATION["runtime"],
        "campaign_run_tag": RUN_TAG,
        "execution_receipt_sha256":
            _EXECUTION_ATTESTATION["receipt_sha256"],
        # Outcome provenance, deliberately outside PROTOCOL_*_HASH.  The
        # anchor is null (anti-cycle); every follower is pinned exactly.
        "block_reference_manifest_sha256":
            _study_block_reference_sha256(),
    }
    block, anchor = execution_block_for_stage(STAGE, EXECUTION_BLOCK_POLICY)
    del block
    if STAGE == anchor and tuple(int(d) for d in dofs) == FULL_DOF_INPUT:
        config["hyperparameter_mode"] = ANCHOR_HPO_MODE
    else:
        if _HYPERPARAMETER_MANIFEST is None:
            raise RuntimeError(
                "frozen candidate requested before the complete block-anchor "
                "HPO manifest was authenticated")
        key = (arch["name_short"], int(seed))
        if key not in _FROZEN_HPO_FIELDS:
            _FROZEN_HPO_FIELDS[key] = select_frozen_config(
                _HYPERPARAMETER_MANIFEST,
                architecture=arch["name_short"],
                seed=int(seed),
                expected_runtime=_EXECUTION_ATTESTATION["runtime"],
                expected_run_tag=RUN_TAG,
                expected_execution_receipt_sha256=
                    _EXECUTION_ATTESTATION["receipt_sha256"],
            )
        config.update(deepcopy(_FROZEN_HPO_FIELDS[key]))
    return config


def run_phase(phase_label: str, dofs: list[int]) -> dict:
    """Run every architecture x every seed on one DOF subset (no per-trial MC).

    One pipeline call per seed: study names carry the seed suffix, so a re-run
    (or a seed added later) only trains the missing studies (pipeline resume).
    """
    db, out, cache = _locs(phase_label, dofs)
    all_configs: list[dict] = []
    for seed in SEEDS:
        configs = [make_config(arch, dofs, seed) for arch in ARCHITECTURES]
        print(f"\n{'#' * 64}\n#  {phase_label}   DOFs={dofs}   targets={TARGET_SUPPORTS}   seed={seed}\n"
              f"#  archs: {[a['name_short'] for a in ARCHITECTURES]}\n{'#' * 64}")
        execute_ablation_pipeline(
            experiment_path = configs,
            database_name   = db,
            output_dir_name = out,
            cache_dir_name  = cache,
            dataset         = DATASET,
            n_trials        = N_TRIALS,
            epochs          = EPOCHS,
            optuna_seed     = seed,
            use_pruner      = USE_PRUNER,
            run_robustness  = False,   # reduced grid: no 30-seed per-trial MC
        )
        all_configs.extend(configs)
    phase = {"phase_label": phase_label, "dofs": list(dofs),
             "configs": all_configs, "db": db,
             "output_dir": out, "cache_dir": cache}
    _RAN_PHASES.append(phase)
    return phase


def _publish_anchor_hpo_manifest(calibration_phase: dict) -> None:
    """Build the immutable 4-architecture x 3-seed anchor calibration record."""

    global _HYPERPARAMETER_MANIFEST, _HYPERPARAMETER_MANIFEST_SHA256
    global _FROZEN_HPO_FIELDS

    block, anchor = execution_block_for_stage(STAGE, EXECUTION_BLOCK_POLICY)
    if STAGE != anchor:
        raise RuntimeError("only an execution-block anchor can publish HPO")
    configs = calibration_phase.get("configs", [])
    expected = {
        (architecture, int(seed))
        for architecture in HPO_ARCHITECTURES
        for seed in SEEDS
    }
    indexed: dict[tuple[str, int], dict] = {}
    for config in configs:
        key = (config["name_short"], int(config["seed"]))
        if key in indexed:
            raise RuntimeError(f"duplicate anchor HPO config {key!r}")
        if tuple(int(d) for d in config["dofs"]) != FULL_DOF_INPUT:
            raise RuntimeError("anchor HPO contains a non-full-array config")
        indexed[key] = config
    if set(indexed) != expected:
        raise RuntimeError(
            "anchor HPO phase is not the complete architecture x seed "
            f"factorial (missing={sorted(expected - set(indexed))!r}, "
            f"extra={sorted(set(indexed) - expected)!r})")

    entries = []
    for architecture in HPO_ARCHITECTURES:
        for seed in SEEDS:
            config = indexed[(architecture, int(seed))]
            study = optuna.load_study(
                study_name=config["name"], storage=calibration_phase["db"])
            plan = derive_execution_plan(
                config,
                dataset_name=DATASET,
                requested_n_trials=N_TRIALS,
                requested_use_pruner=USE_PRUNER,
                execution_runtime=_EXECUTION_ATTESTATION["runtime"],
            )
            validate_terminal_study(study, plan)
            entry = study.user_attrs.get(
                "ttbi_hyperparameter_manifest_entry")
            if not isinstance(entry, dict):
                raise RuntimeError(
                    f"{study.study_name}: completed anchor study lacks its "
                    "authenticated HPO manifest entry")
            entries.append(entry)

    manifest, expected_sha = build_manifest(
        entries,
        execution_runtime=_EXECUTION_ATTESTATION["runtime"],
        protocol_core_hash=PROTOCOL_CORE_HASH,
        anchor_protocol_hash=PROTOCOL_HASH,
        anchor_dataset=DATASET,
        run_tag=RUN_TAG,
        execution_receipt_sha256=
            _EXECUTION_ATTESTATION["receipt_sha256"],
    )
    if os.path.lexists(HYPERPARAMETER_MANIFEST):
        try:
            existing = load_hyperparameter_manifest(
                HYPERPARAMETER_MANIFEST,
                expected_sha256=expected_sha,
                expected_runtime=_EXECUTION_ATTESTATION["runtime"],
                expected_run_tag=RUN_TAG,
                expected_execution_receipt_sha256=
                    _EXECUTION_ATTESTATION["receipt_sha256"],
            )
        except HyperparameterPolicyError as exc:
            raise RuntimeError(
                "existing block HPO manifest differs from the completed anchor "
                "calibration; use a fresh RUN_TAG/path, never overwrite it"
            ) from exc
        if existing != manifest:
            raise RuntimeError("HPO manifest canonical equality failure")
    else:
        written_sha = write_hyperparameter_manifest(
            HYPERPARAMETER_MANIFEST,
            manifest,
            expected_runtime=_EXECUTION_ATTESTATION["runtime"],
            expected_run_tag=RUN_TAG,
            expected_execution_receipt_sha256=
                _EXECUTION_ATTESTATION["receipt_sha256"],
        )
        if written_sha != expected_sha:
            raise RuntimeError("published HPO manifest SHA-256 mismatch")
    _HYPERPARAMETER_MANIFEST = manifest
    _HYPERPARAMETER_MANIFEST_SHA256 = expected_sha
    _FROZEN_HPO_FIELDS = {}
    print(
        f"[HPO] authenticated {block}/{anchor} full-array calibration: "
        f"{HYPERPARAMETER_MANIFEST} sha256={expected_sha}"
    )


